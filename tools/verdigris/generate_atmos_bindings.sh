#!/bin/bash
# Regenerate modular_dq/code/atmospherics/auxmos_bindings.dm from auxmos's
# generate_binds output. Post-processes the result so that auxmos's bind procs
# call into our combined libverdigris.so (instead of a separate libauxmos.so).
#
# Run after any auxmos vendor bump.
#
# Usage: bash tools/verdigris/generate_atmos_bindings.sh

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
WORKSPACE_ROOT="$REPO_ROOT/verdigris"
RAW_BINDINGS="$WORKSPACE_ROOT/atmos/bindings.dm"
OUT="$REPO_ROOT/modular_dq/code/atmospherics/auxmos_bindings.dm"

cd "$WORKSPACE_ROOT"

# byondapi-sys triggers compile_error on non-x86 targets, so we must pick a 32-bit target.
# On Linux CI runners use the GNU target; on Windows dev machines use MSVC.
case "$(uname -s)" in
    Linux*)   CARGO_TARGET="i686-unknown-linux-gnu" ;;
    MINGW*|MSYS*|CYGWIN*|Windows*) CARGO_TARGET="i686-pc-windows-msvc" ;;
    Darwin*)  echo "macOS is not supported (BYOND/byondapi is Windows+Linux only)" >&2; exit 1 ;;
    *)        echo "Unknown OS: $(uname -s)" >&2; exit 1 ;;
esac

# auxmos's generate_binds is feature-gated; mirror the verdigris dependency's feature set.
cargo test \
    --target "$CARGO_TARGET" \
    --package auxmos \
    --features katmos,katmos_slow_decompression \
    -- generate_binds --nocapture >/dev/null

if [[ ! -f "$RAW_BINDINGS" ]]; then
    echo "ERROR: $RAW_BINDINGS was not produced by cargo test generate_binds" >&2
    exit 1
fi

mkdir -p "$(dirname "$OUT")"

# Post-process with awk:
#   - Skip auxmos's autogen banner (first two lines) and library-detection block
#     (the __auxmos var + __detect_auxmos proc + AUXMOS macro define).
#   - Substitute call_ext(AUXMOS, ...) -> call_ext(VERDIGRIS, ...) so the procs
#     route via verdigris's existing library detector.
#   - Prepend our own header explaining provenance.

{
    cat <<'EOF'
// AUTOGENERATED — DO NOT EDIT BY HAND
// Source: verdigris/atmos/bindings.dm (output of cargo t generate_binds with
// features katmos,katmos_slow_decompression)
// Post-processed by tools/verdigris/generate_atmos_bindings.sh to route via VERDIGRIS.
// To regenerate: bash tools/verdigris/generate_atmos_bindings.sh
// See modular_dq/doc/atmos_migration.md.

EOF

    awk '
        # Skip auxmos autogen banner
        NR <= 2 { next }
        # Skip the library detection block: starts at the __auxmos var line,
        # ends at the AUXMOS macro define.
        /^\/\* This comment bypasses grep checks \*\/ \/var\/__auxmos[[:space:]]*$/ { skipping=1; next }
        skipping && /^#define AUXMOS[[:space:]]*\(__auxmos[[:space:]]*\|\|[[:space:]]*__detect_auxmos\(\)\)[[:space:]]*$/ { skipping=0; next }
        skipping { next }
        # Route through verdigris.
        { gsub(/call_ext\(AUXMOS,/, "call_ext(VERDIGRIS,"); print }
    ' "$RAW_BINDINGS"
} > "$OUT"

echo "wrote $OUT ($(wc -l < "$OUT") lines)" >&2
