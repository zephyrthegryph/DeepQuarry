mod original;
use dq_analyze::sem::gen::{GenCx,GenOut,Generator};
use dq_analyze::run::{registry,Engine,Options};
use std::path::PathBuf;
fn generate(g:&dyn Generator,cx:&GenCx<'_>)->(String,Vec<(String,u32,String)>){
    // Invoke both actual producers: render()'s same-name stored answer would
    // otherwise let the second side reuse the first side without running it.
    let mut out=GenOut::default();
    g.generate(cx,&mut out);
    let mut text=format!("// GENERATED by tools/analyze: `analyze gen {}`. Do not edit by hand; edit the declarations it reads.\n// Written to code/engine/_generated/{}; not committed: every build regenerates it (`analyze gen`).\n\n",g.name(),g.output());
    text.push_str(out.text());if !text.ends_with('\n'){text.push('\n');}
    (text,out.diags.into_iter().map(|d|(d.rel,d.line,d.msg)).collect())
}
fn main()->Result<(),Box<dyn std::error::Error>>{
    let root=PathBuf::from(std::env::args().nth(1).ok_or("fixture root required")?);
    let root=if root.is_absolute(){root}else{std::env::current_dir()?.join(root)};
    let engine=Engine::new(registry(),Options{root:root.clone(),scopes_from:Some(root.clone()),raw:true,no_cache:true,..Default::default()})?;
    let sem=sem::sem_for(&engine.tree).ok_or("independent original semantic owner unavailable")?;
    if !sem.errors.is_empty(){return Err(format!("old fixture parse errors: {:?}",sem.errors).into());}
    let mut old=Vec::new();original::register(&mut old);
    let mut actual=Vec::new();dq_analyze::gens::register(&mut actual);
    let actual=actual.iter().find(|g|g.name()=="plans").ok_or("shared plans producer missing")?;
    let cx=GenCx::new(&engine.tree,&root);
    let expected=generate(old[0].as_ref(),&cx);
    let observed=generate(actual.as_ref(),&cx);
    // Full exact file includes the existing name/output preamble and every
    // table/chunk/order/whitespace byte; diagnostics retain their order.
    if expected!=observed{return Err(format!("complete plans policy mismatch\nold={expected:#?}\nshared={observed:#?}").into());}
    let expected_families=std::fs::read_to_string(root.join("expected_plans_fragments.txt"))?;
    for needle in expected_families.lines().filter(|s|!s.is_empty()&&!s.starts_with('#')){
        if !expected.0.contains(needle){return Err(format!("independent original fixture did not exercise {needle:?}").into());}
    }
    println!("plans original/shared complete body exact: {} bytes, {} diagnostics",expected.0.len(),expected.1.len());
    let previous_temp:Vec<_>=["TEMP","TMP","TMPDIR"].into_iter().map(|key|(key,std::env::var_os(key))).collect();
    let negative=unavailable_model_oracle(&root,old[0].as_ref(),actual.as_ref());
    if previous_temp.iter().any(|(key,value)|std::env::var_os(key)!=*value){return Err("negative oracle failed to restore process temp environment".into());}
    negative?;
    if generate(old[0].as_ref(),&cx)!=expected{return Err("original positive producer changed after unavailable-model oracle".into());}
    Ok(())
}

// Process-local oracle fault domain only. It exercises the ORIGINAL real
// tempfile creation/write failure; no semantic answer/cache entry is injected.
struct TempEnvironment(Vec<(&'static str,Option<std::ffi::OsString>)>);
impl TempEnvironment{
 fn blocked(path:&std::path::Path)->Self{
  let previous=["TEMP","TMP","TMPDIR"].into_iter().map(|key|{let previous=std::env::var_os(key);std::env::set_var(key,path);(key,previous)}).collect();Self(previous)
 }
}
impl Drop for TempEnvironment{fn drop(&mut self){for(key,value)in self.0.drain(..){match value{Some(v)=>std::env::set_var(key,v),None=>std::env::remove_var(key)}}}}
fn unavailable_model_oracle(positive_root:&std::path::Path,old:&dyn Generator,actual:&dyn Generator)->Result<(),Box<dyn std::error::Error>>{
 let root=std::env::args().nth(2).map(PathBuf::from).unwrap_or_else(||positive_root.with_file_name("plans-model-unavailable"));
 let root=if root.is_absolute(){root}else{std::env::current_dir()?.join(root)};
 let blocked=root.join("temp-not-directory");
 if !blocked.is_file(){return Err("negative plans fixture requires the real regular-file temp root".into());}
 let text=std::fs::read_to_string(root.join("code/probe.dm"))?;
 let mut tree=tree::Tree::from_files(vec![tree::SourceFile::from_text("code/probe.dm",&text)]);tree.root=root.clone();
 let _environment=TempEnvironment::blocked(&blocked);
 if std::env::temp_dir()!=blocked{return Err("platform did not select the blocked oracle temp root".into());}
 // A fresh, genuine original Tree memo reaches the actual failed filesystem
 // operation. Reusing a manually seeded None would not prove this branch.
 if sem::sem_for(&tree).is_some(){return Err("negative original model unexpectedly succeeded".into());}
 let cx=GenCx::new(&tree,&root);let expected=generate(old,&cx);let observed=generate(actual,&cx);
 if expected.1.len()!=1{return Err(format!("independent old plans model-failure fixture needs its one diagnostic, got {:?}",expected.1).into());}
 if expected!=observed{return Err(format!("complete failed-model plans output/ordered diagnostics differ\nold={expected:#?}\nshared={observed:#?}").into());}
 println!("plans original/shared actual unavailable-model case exact: {} bytes, {} ordered diagnostics",expected.0.len(),expected.1.len());Ok(())
}
