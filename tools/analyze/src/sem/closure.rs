//! `analyze sem closure [--write]`: what changed when the lints moved from the legacy read walk to the closed walk.
//!
//! The lints (`untracked_inputs`, `sem/reads`) used to judge handlers with a walk that skipped the engine-internal directories, followed a
//! call on the receiver's static type only and stopped at every global proc without `READS_FROM`. They now judge the closed walk
//! ([`ReadsEngine::closed`], the one the generated subscriptions already used): engine bodies are entered, a virtual call is the union of its
//! overrides, a global proc is walked like any other, and global state is classified (`sem/globals.rs`). The two are compared here: what only
//! the closed walk finds was invisible to the old baseline (the measurement changed; the code did not), and what only the old walk reported
//! was a site the closed walk walks into and resolves.
//!
//! `--write` writes `doc/rewrite/reads_closure_newly_visible.md`; without it the report goes to stdout.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use crate::gens::deps::{self, DepsAnalysis};
use crate::sem::reads::ENGINE_DIRS;
use crate::tree::Tree;

/// A site as the baseline sees it: the rule (`draw_untracked` / `stat_input_untracked`), the file, the line, and what is read.
type Spot = (String, String, u32, String);

/// Every spot of an analysis with the consumers that reach it.
fn spots(a: &DepsAnalysis) -> BTreeMap<Spot, BTreeSet<String>> {
    let mut out: BTreeMap<Spot, BTreeSet<String>> = BTreeMap::new();
    for (id, reads) in &a.consumers {
        let rule = if a.draws.contains(id) { "draw_untracked" } else { "stat_input_untracked" };
        for u in reads {
            if u.rel.is_empty() || u.line == 0 {
                continue;
            }
            out.entry((rule.to_string(), u.rel.clone(), u.line, u.what.clone())).or_default().insert(id.clone());
        }
    }
    out
}

/// The category of a site's `what`.
fn category(what: &str) -> &'static str {
    match what {
        w if w.starts_with("?opaque:") => "opaque crossing",
        "?unannotated_global" => "unannotated global proc",
        "?dynamic_read" => "vars[] / call()",
        "?hop_not_relation" => "hop through a non-relation var",
        "?ffi_call" => "Verdigris FFI call",
        w if w.starts_with("GLOB.") || w.starts_with("SS") && !w.contains(' ') && w.chars().nth(2).map(|c| c.is_ascii_lowercase()).unwrap_or(false) => "dynamic global state",
        _ => "untracked var read",
    }
}

/// `code/game/` style: the first two path components.
fn area(rel: &str) -> String {
    rel.split('/').take(2).collect::<Vec<_>>().join("/")
}

fn in_engine(rel: &str) -> bool {
    ENGINE_DIRS.iter().any(|d| rel.starts_with(d))
}

fn tally<'a, K: Ord>(items: impl Iterator<Item = &'a Spot>, key: impl Fn(&Spot) -> K) -> BTreeMap<K, usize> {
    let mut m = BTreeMap::new();
    for s in items {
        *m.entry(key(s)).or_insert(0) += 1;
    }
    m
}

pub fn report(tree: &Tree) -> Option<String> {
    let base = deps::analyzed_legacy(tree);
    let closed = deps::analyzed(tree);
    let (base, closed) = (base.as_ref().as_ref()?, closed.as_ref().as_ref()?);
    let (before, after) = (spots(base), spots(closed));
    let new: BTreeMap<&Spot, &BTreeSet<String>> = after.iter().filter(|(k, _)| !before.contains_key(*k)).collect();
    let gone = before.keys().filter(|k| !after.contains_key(*k)).count();
    let new_keys = || new.keys().copied();
    let engine_side = new_keys().filter(|s| in_engine(&s.1)).count();
    let count = |m: &BTreeMap<Spot, BTreeSet<String>>, rule: &str| m.keys().filter(|s| s.0 == rule).count();

    let mut out = String::new();
    let _ = writeln!(out, "# Reads closure\n");
    let _ = writeln!(out, "Generated by `analyze sem closure --write`. Do not edit by hand; it is deterministic for a tree.\n\n");
    let _ = writeln!(out, "`untracked_inputs` and `sem/reads` used to judge a read walk that skipped the engine-internal directories, followed a call on the receiver's static type only and");
    let _ = writeln!(out, "stopped at every global proc without `READS_FROM`. They now judge the closed walk (`ReadsEngine::closed`, the one the generated subscriptions already used): engine bodies are");
    let _ = writeln!(out, "entered, a virtual call is the union of its overrides, a global proc is walked like any proc, and global state is classified (`sem/globals.rs`: written only while the world boots,");
    let _ = writeln!(out, "so it reads like a constant; a tracked var of a system; anything else is an input nothing publishes). **This is a change of measurement, not new debt.** The baselines were");
    let _ = writeln!(out, "re-seeded once, counted per site (a line read by six hundred draws is one line), and only shrink from here. Legacy walk below is the old measurement, closed walk the new one.\n");
    let _ = writeln!(out, "| | draw_untracked | stat_input_untracked | total |\n|---|---:|---:|---:|");
    let _ = writeln!(out, "| legacy walk | {} | {} | {} |", count(&before, "draw_untracked"), count(&before, "stat_input_untracked"), before.len());
    let _ = writeln!(out, "| closed walk | {} | {} | {} |", count(&after, "draw_untracked"), count(&after, "stat_input_untracked"), after.len());
    let newd = new_keys().filter(|s| s.0 == "draw_untracked").count();
    let _ = writeln!(out, "| **newly visible** | {} | {} | {} |", newd, new.len() - newd, new.len());
    let _ = writeln!(out, "| no longer reported (walked into) | | | {} |\n", gone);
    // The baseline file holds one line per (consumer, line): the number a baseline decision has to cover.
    let units = |it: &mut dyn Iterator<Item = (&Spot, &BTreeSet<String>)>, rule: &str| it.filter(|(s, _)| s.0 == rule).map(|(_, c)| c.len()).sum::<usize>();
    let (bd, bs) = (units(&mut before.iter(), "draw_untracked"), units(&mut before.iter(), "stat_input_untracked"));
    let (cd, cs) = (units(&mut after.iter(), "draw_untracked"), units(&mut after.iter(), "stat_input_untracked"));
    let (nd, ns) = (units(&mut new.iter().map(|(k, v)| (*k, *v)), "draw_untracked"), units(&mut new.iter().map(|(k, v)| (*k, *v)), "stat_input_untracked"));
    let _ = writeln!(out, "The same, counted the way the old `untracked_inputs_baseline.txt` counted (one line per consumer that reaches a site, so a helper line read by ten draws is ten lines; the new baseline counts sites, the table above):\n");
    let _ = writeln!(out, "| | draw_untracked | stat_input_untracked | total |\n|---|---:|---:|---:|");
    let _ = writeln!(out, "| legacy walk | {} | {} | {} |", bd, bs, bd + bs);
    let _ = writeln!(out, "| closed walk | {} | {} | {} |", cd, cs, cd + cs);
    let _ = writeln!(out, "| **newly visible** | {} | {} | {} |\n", nd, ns, nd + ns);

    let _ = writeln!(out, "## Newly visible, by category\n");
    let _ = writeln!(out, "| category | draw | stat input | total |\n|---|---:|---:|---:|");
    let by_cat = tally(new_keys(), |s| (category(&s.3), s.0.clone()));
    let cats: BTreeSet<&str> = by_cat.keys().map(|k| k.0).collect();
    for c in cats {
        let d = by_cat.get(&(c, "draw_untracked".to_string())).copied().unwrap_or(0);
        let st = by_cat.get(&(c, "stat_input_untracked".to_string())).copied().unwrap_or(0);
        let _ = writeln!(out, "| {} | {} | {} | {} |", c, d, st, d + st);
    }
    let _ = writeln!(out, "\nOf the {} newly visible sites, **{}** sit in engine-internal files (the directories the lints' walk skips) and {} in content reached through a virtual call or through the engine.\n", new.len(), engine_side, new.len() - engine_side);

    let _ = writeln!(out, "## Newly visible, by area\n");
    let _ = writeln!(out, "| area | sites |\n|---|---:|");
    let mut areas: Vec<(String, usize)> = tally(new_keys(), |s| area(&s.1)).into_iter().collect();
    areas.sort_by(|a, b| b.1.cmp(&a.1).then(a.0.cmp(&b.0)));
    for (a, n) in areas.iter().take(40) {
        let _ = writeln!(out, "| `{}` | {} |", a, n);
    }

    let _ = writeln!(out, "\n## Newly visible, top files\n");
    let _ = writeln!(out, "| file | sites |\n|---|---:|");
    let mut files: Vec<(String, usize)> = tally(new_keys(), |s| s.1.clone()).into_iter().collect();
    files.sort_by(|a, b| b.1.cmp(&a.1).then(a.0.cmp(&b.0)));
    for (f, n) in files.iter().take(40) {
        let _ = writeln!(out, "| `{}` | {} |", f, n);
    }

    // The engine's own unresolved constructs: the procs that genuinely cannot be walked and want a PROC_SUMMARY.
    let _ = writeln!(out, "\n## Constructs the walk cannot resolve inside the engine (want a `PROC_SUMMARY`)\n");
    let _ = writeln!(out, "`vars[]`/`call()`, a global proc without `READS_FROM`, a Verdigris FFI call, or a hop through a var that is not a declared relation, found in an engine-internal body.");
    let _ = writeln!(out, "`PROC_SUMMARY(path, reads = list(...), writes = list(...))` (`code/__defines/engine/markers.dm`) declares what such a proc touches; the walk then takes the summary in place of the body.\n");
    let mut unwalkable: BTreeMap<(String, &'static str), BTreeSet<u32>> = BTreeMap::new();
    for s in new_keys().filter(|s| in_engine(&s.1)) {
        let c = category(&s.3);
        if c != "untracked var read" {
            unwalkable.entry((s.1.clone(), c)).or_default().insert(s.2);
        }
    }
    let _ = writeln!(out, "| file | construct | lines |\n|---|---|---|");
    for ((f, c), lines) in &unwalkable {
        let ls: Vec<String> = lines.iter().take(12).map(|l| l.to_string()).collect();
        let _ = writeln!(out, "| `{}` | {} | {}{} |", f, c, ls.join(", "), if lines.len() > 12 { ", ..." } else { "" });
    }
    if unwalkable.is_empty() {
        let _ = writeln!(out, "| (none) | | |");
    }
    let ffi: BTreeSet<String> = new_keys()
        .filter(|s| s.3 == "?ffi_call")
        .filter_map(|s| tree.get(&s.1).and_then(|f| f.raw().text.split('\n').nth(s.2 as usize - 1).map(|l| l.to_string())))
        .flat_map(|l| crate::pat!(r"\bvg_\w+").find_iter(&l).into_iter().map(|m| m.as_str().to_string()).collect::<Vec<_>>())
        .collect();
    let _ = writeln!(out, "\nVerdigris FFI procs a handler or draw reaches ({}): {}\n", ffi.len(), ffi.iter().map(|f| format!("`{}`", f)).collect::<Vec<_>>().join(", "));

    let _ = writeln!(out, "## Every newly visible site\n");
    let _ = writeln!(out, "`rule | file:line | read | consumers reaching it`\n");
    for (s, consumers) in &new {
        let _ = writeln!(out, "- {} | {}:{} | `{}` | {}", s.0, s.1, s.2, s.3, consumers.len());
    }
    Some(out)
}

/// The `analyze sem closure` command.
pub fn run(tree: &Tree, root: &std::path::Path, write: bool) -> std::process::ExitCode {
    let Some(text) = report(tree) else {
        eprintln!("analyze sem closure: the semantic model could not be built");
        return std::process::ExitCode::from(2);
    };
    if write {
        let path = root.join("doc/rewrite/reads_closure_newly_visible.md");
        if let Err(e) = std::fs::write(&path, &text) {
            eprintln!("analyze sem closure: {}: {}", path.display(), e);
            return std::process::ExitCode::from(2);
        }
        println!("wrote {}", path.display());
    } else {
        print!("{}", text);
    }
    std::process::ExitCode::SUCCESS
}
