//! Exact sparse_slots row policy, shared by legacy and native producers.
#[derive(Clone, Debug, PartialEq, Eq, serde::Serialize)]
pub struct Diagnostic {
    pub rel: String,
    pub line: u32,
    pub msg: String,
}
#[derive(Clone, Debug, Default, serde::Serialize)]
pub struct Output {
    pub body: String,
    pub diags: Vec<Diagnostic>,
    #[serde(skip)]
    budget: Option<std::sync::Arc<crate::captured_generator_budget::Budget>>,
}
impl PartialEq for Output {
    fn eq(&self, other: &Self) -> bool {
        self.body == other.body && self.diags == other.diags
    }
}
impl Eq for Output {}
/// One exactly funded named file during a closed probe. The String always
/// dies before its root Budget reservation, including an early failure.
pub(crate) struct CapturedNamedFile {
    text: String,
    _window: crate::captured_generator_budget::ReservedWindow,
}
impl CapturedNamedFile {
    pub(crate) fn as_str(&self) -> &str { &self.text }
}
impl Output {
    pub(crate) fn captured(
        budget: std::sync::Arc<crate::captured_generator_budget::Budget>,
    ) -> Self {
        Self {
            budget: Some(budget),
            ..Default::default()
        }
    }
    /// Shared exact generator preamble; named borrowed generators use the same
    /// per-write admission as the original sparse renderer.
    pub fn write_named_file_text(
        &self,
        name: &str,
        filename: &str,
        out: &mut impl std::fmt::Write,
    ) -> std::fmt::Result {
        write!(out, "// GENERATED by tools/analyze: `analyze gen {}`. Do not edit by hand; edit the declarations it reads.\n// Written to code/engine/_generated/{}; not committed: every build regenerates it (`analyze gen`).\n\n", name, filename)?;
        out.write_str(&self.body)?;
        if !self.body.is_empty() && !self.body.ends_with('\n') {
            out.write_str("\n")?;
        }
        Ok(())
    }
    pub fn captured_named_file_text(
        &self,
        name: &str,
        filename: &str,
        budget: &crate::captured_generator_budget::Budget,
    ) -> Result<String, String> {
        let mut out = crate::captured_generator_budget::BudgetedText::new(budget);
        self.write_named_file_text(name, filename, &mut out)
            .map_err(|_| "captured generator renderer allocation denied".to_owned())?;
        out.finish()
    }

    /// One admission and one allocation for the exact current named bytes.
    /// Both passes use the existing renderer. The returned owner cannot
    /// refund the backing while a caller still borrows the staged text.
    pub(crate) fn capture_exact_named_file(
        &self,
        name: &str,
        filename: &str,
        budget: &std::sync::Arc<crate::captured_generator_budget::Budget>,
    ) -> std::io::Result<CapturedNamedFile> {
        use std::{alloc::Layout, fmt, io, ptr::NonNull};
        struct Count(usize);
        impl fmt::Write for Count {
            fn write_str(&mut self, text: &str) -> fmt::Result {
                self.0 = self.0.checked_add(text.len()).ok_or(fmt::Error)?;
                Ok(())
            }
        }
        struct Fixed(String);
        impl fmt::Write for Fixed {
            fn write_str(&mut self, text: &str) -> fmt::Result {
                if text.len() > self.0.capacity() - self.0.len() { return Err(fmt::Error); }
                self.0.push_str(text);
                Ok(())
            }
        }
        let denied = || io::Error::from(io::ErrorKind::OutOfMemory);
        let mut width = Count(0);
        self.write_named_file_text(name, filename, &mut width).map_err(|_| denied())?;
        let layout = Layout::array::<u8>(width.0).map_err(|_| denied())?;
        // The common renderer always emits its preamble.
        if layout.size() == 0 { return Err(io::ErrorKind::InvalidData.into()); }
        let window = crate::captured_generator_budget::Budget::reserve_window(budget, layout.size())
            .map_err(|message| io::Error::new(io::ErrorKind::OutOfMemory, message))?;
        if window.capacity() != layout.size() { return Err(denied()); }
        // SAFETY: admitted nonzero Layout for an ordinary Global Vec<u8>.
        // The unique Vec starts empty, and every following byte is UTF-8.
        let data = NonNull::new(unsafe { std::alloc::alloc(layout) }).ok_or_else(denied)?;
        let bytes = unsafe { Vec::from_raw_parts(data.as_ptr(), 0, layout.size()) };
        let mut out = Fixed(String::from_utf8(bytes).expect("empty UTF8 backing"));
        self.write_named_file_text(name, filename, &mut out).map_err(|_| io::ErrorKind::InvalidData)?;
        if out.0.len() != layout.size() { return Err(io::ErrorKind::InvalidData.into()); }
        Ok(CapturedNamedFile { text: out.0, _window: window })
    }

    pub fn line(&mut self, s: impl AsRef<str>) {
        self.line_fmt(format_args!("{}", s.as_ref()));
    }
    pub fn line_fmt(&mut self, args: std::fmt::Arguments<'_>) {
        if let Some(budget) = &self.budget {
            if !budget.append_fmt(&mut self.body, args) {
                return;
            }
            budget.string(&mut self.body, "\n");
        } else {
            use std::fmt::Write;
            self.body.write_fmt(args).expect("String writer");
            self.body.push('\n');
        }
    }
    pub fn doc(&mut self, s: impl AsRef<str>) {
        self.doc_fmt(format_args!("{}", s.as_ref()));
    }
    pub fn doc_fmt(&mut self, args: std::fmt::Arguments<'_>) {
        self.line_fmt(format_args!("/// {}", args));
    }
    pub fn blank(&mut self) {
        self.line("");
    }
    pub fn diag(&mut self, rel: &str, line: u32, msg: impl std::fmt::Display) {
        self.diag_fmt(rel, line, format_args!("{}", msg));
    }
    pub fn diag_fmt(&mut self, rel: &str, line: u32, args: std::fmt::Arguments<'_>) {
        let (rel, msg) = if let Some(budget) = &self.budget {
            if self.diags.len() >= crate::captured_generator_budget::MAX_ROWS
                || !budget.row(&mut self.diags)
            {
                budget.deny();
                return;
            }
            let mut owned_rel = String::new();
            if !budget.string(&mut owned_rel, rel) {
                return;
            }
            let mut owned_msg = String::new();
            if !budget.append_fmt(&mut owned_msg, args) {
                return;
            }
            (owned_rel, owned_msg)
        } else {
            (rel.to_owned(), args.to_string())
        };
        self.diags.push(Diagnostic { rel, line, msg });
    }
    pub fn write_file_text(&self, out: &mut impl std::fmt::Write) -> std::fmt::Result {
        self.write_named_file_text("sparse_slots", "sparse_slots.dm", out)
    }
    pub fn file_text(&self) -> String {
        let mut text = String::new();
        self.write_file_text(&mut text)
            .expect("String writer is infallible");
        text
    }
    pub fn captured_file_text(
        &self,
        budget: &crate::captured_generator_budget::Budget,
    ) -> Result<String, String> {
        let mut text = crate::captured_generator_budget::BudgetedText::new(budget);
        self.write_file_text(&mut text)
            .map_err(|_| "captured generator renderer allocation denied".to_owned())?;
        text.finish()
    }
}
#[derive(Default)]
pub struct Builder {
    rows: Vec<(String, String, String, String, u32)>,
    out: Output,
}
impl Builder {
    pub(crate) fn captured(
        budget: std::sync::Arc<crate::captured_generator_budget::Budget>,
    ) -> Self {
        Self {
            rows: Vec::new(),
            out: Output {
                budget: Some(budget),
                ..Default::default()
            },
        }
    }

    pub fn push(&mut self, rel: &str, line: u32, args: &[String]) {
        let (Some(owner), Some(name)) = (args.first(), args.get(1)) else {
            self.out.diag(
                rel,
                line,
                "sparse(/type, name, type = kind) needs a type and a slot name",
            );
            return;
        };
        let owner = owner.trim().to_string();
        let name = name.trim().to_string();
        if !owner.starts_with('/')
            || name.is_empty()
            || !name.chars().all(|c| c.is_alphanumeric() || c == '_')
        {
            self.out.diag(
                rel,
                line,
                format_args!(
                    "sparse: `{}`, `{}` is not a type path and a slot name",
                    owner, name
                ),
            );
            return;
        }
        let kind = args
            .iter()
            .skip(2)
            .find_map(|a| {
                a.trim()
                    .strip_prefix("type")
                    .map(|r| r.trim_start())
                    .and_then(|r| r.strip_prefix('='))
                    .map(|r| r.trim().to_string())
            })
            .unwrap_or_default();
        self.rows.push((owner, name, kind, rel.to_string(), line));
    }
    pub fn finish(self)->Output{self.finish_with(&mut||Ok::<(),std::convert::Infallible>(())).unwrap_or_else(|never|match never{})}
    /// Same output policy; checkpoint failures never use String transport.
    pub fn finish_with<E>(self,checkpoint:&mut impl FnMut()->Result<(),E>)->Result<Output,E>{
        checkpoint()?;let Self { mut rows, mut out } = self;
        rows.sort();
        for w in rows.windows(2) {
            checkpoint()?;
            if w[0].0 == w[1].0 && w[0].1 == w[1].1 {
                out.diag_fmt(
                    &w[1].3,
                    w[1].4,
                    format_args!(
                        "sparse slot `{}` of {} is declared twice (also {}:{})",
                        w[1].1, w[1].0, w[0].3, w[0].4
                    ),
                );
            }
        }
        rows.dedup_by(|a, b| a.0 == b.0 && a.1 == b.1);
        out.doc("Every sparse() slot declaration: list(owner type, slot name, value kind). Read by code/engine/declare/sparse_vv.dm.");
        out.line("/proc/sparse_slot_rows()");
        out.line("	var/static/list/rows = list(");
        let last = rows.len().saturating_sub(1);
        for (i, (owner, name, kind, _, _)) in rows.iter().enumerate() {
            checkpoint()?;
            let comma = if i == last { "" } else { "," };
            out.line_fmt(format_args!(
                "		list({}, \"{}\", \"{}\"){}",
                owner, name, kind, comma
            ));
        }
        out.line("	)");
        out.line("	return rows");
        checkpoint()?;Ok(out)
    }
}

