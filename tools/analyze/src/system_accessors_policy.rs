//! Exact SYSTEM_ACCESSOR generator row policy shared by both source producers.
pub use crate::sparse_slots_policy::Diagnostic;
use std::collections::HashSet;
#[derive(Clone, Debug, Default, PartialEq, Eq, serde::Serialize)]
pub struct Output {
    pub body: String,
    pub diags: Vec<Diagnostic>,
}
impl Output {
    pub fn line(&mut self, s: impl AsRef<str>) {
        self.body.push_str(s.as_ref());
        self.body.push('\n');
    }
    pub fn doc(&mut self, s: impl AsRef<str>) {
        self.line(format!("/// {}", s.as_ref()));
    }
    pub fn blank(&mut self) {
        self.line("");
    }
    pub fn diag(&mut self, rel: &str, line: u32, msg: impl Into<String>) {
        self.diags.push(Diagnostic {
            rel: rel.to_string(),
            line,
            msg: msg.into(),
        });
    }
    pub fn file_text(&self) -> String {
        let mut out=String::from("// GENERATED by tools/analyze: `analyze gen system_accessors`. Do not edit by hand; edit the declarations it reads.\n// Written to code/engine/_generated/system_accessors.dm; not committed: every build regenerates it (`analyze gen`).\n\n");
        out.push_str(&self.body);
        if !out.ends_with('\n') {
            out.push('\n');
        }
        out
    }
}
pub fn system_types(system: &str) -> Vec<String> {
    vec![
        format!("/datum/world_service/{}", system),
        format!("/datum/system/{}", system),
    ]
}
pub fn visit_system_defs(
    raw: &str,
    mut visit: impl FnMut(&str) -> Result<(), String>,
) -> Result<(), String> {
    if raw.contains("SYSTEM_DEF(") {
        for c in crate::pat!(r"(?m)^\s*SYSTEM_DEF\((\w+)\)").captures_iter(raw) {
            visit(c.s(1))?;
        }
    }
    Ok(())
}
pub fn system_defs(raw: &str) -> Vec<String> {
    let mut defs = Vec::new();
    visit_system_defs(raw, |name| {
        defs.push(name.to_owned());
        Ok(())
    })
    .expect("infallible collector");
    defs
}
/// Exact file selection of sem::gen::system_vars, including prefix matches.
pub fn file_mentions_system(code: &str, system: &str) -> bool {
    let plain = !system.is_empty() && system.chars().all(|c| c.is_alphanumeric() || c == '_');
    if !plain {
        return system_types(system).iter().any(|t| code.contains(t));
    }
    for prefix in ["/datum/world_service/", "/datum/system/"] {
        let mut from = 0;
        while let Some(i) = code[from..].find(prefix) {
            let start = from + i + prefix.len();
            let run: String = code[start..]
                .chars()
                .take_while(|c| c.is_alphanumeric() || *c == '_')
                .collect();
            if run.starts_with(system) {
                return true;
            }
            from = start;
        }
    }
    false
}
pub struct Builder {
    sys_defs: HashSet<String>,
    rows: Vec<(String, String, String, String, u32, Option<String>)>,
    out: Output,
}
impl Builder {
    pub fn new(sys_defs: HashSet<String>) -> Self {
        Self {
            sys_defs,
            rows: Vec::new(),
            out: Output::default(),
        }
    }
    pub fn push(
        &mut self,
        rel: &str,
        line: u32,
        args: &[String],
        has_var: impl Fn(&str, &str) -> bool,
    ) {
        let (Some(system), Some(name), Some(key)) = (args.first(), args.get(1), args.get(2)) else {
            self.out.diag(
                rel,
                line,
                "SYSTEM_ACCESSOR(system, name, nameof(var)) needs three arguments",
            );
            return;
        };
        let Some(var) = key
            .trim()
            .strip_prefix("nameof(")
            .and_then(|s| s.strip_suffix(')'))
            .map(|s| s.trim().to_string())
        else {
            self.out.diag(
                rel,
                line,
                format!(
                    "accessor `{}`: the third argument is nameof(var), not `{}`",
                    name, key
                ),
            );
            return;
        };
        if !has_var(system, &var) {
            self.out.diag(
                rel,
                line,
                format!(
                    "accessor `{}`: system `{}` has no var `{}` (looked at {})",
                    name,
                    system,
                    var,
                    system_types(system).join(", ")
                ),
            );
            return;
        }
        let typed = match args.get(3).map(|t| t.trim().to_string()) {
            None => None,
            Some(t)
                if t.starts_with('/')
                    && t[1..]
                        .chars()
                        .all(|c| c.is_alphanumeric() || c == '_' || c == '/') =>
            {
                Some(t)
            }
            Some(t) => {
                self.out.diag(
                    rel,
                    line,
                    format!(
                        "accessor `{}`: the fourth argument is the var's type path, not `{}`",
                        name, t
                    ),
                );
                return;
            }
        };
        self.rows.push((
            name.clone(),
            system.clone(),
            var,
            rel.to_string(),
            line,
            typed,
        ));
    }
    pub fn finish(self) -> Output {
        let Self {
            sys_defs,
            mut rows,
            mut out,
        } = self;
        let instance = |system: &str| {
            if sys_defs.contains(system) {
                format!("SS{}", system)
            } else {
                format!("GLOB.{}_service", system)
            }
        };
        rows.sort();
        for w in rows.windows(2) {
            if w[0].0 == w[1].0 {
                out.diag(
                    &w[1].3,
                    w[1].4,
                    format!(
                        "accessor `{}` is declared twice (also {}:{})",
                        w[0].0, w[0].3, w[0].4
                    ),
                );
            }
        }
        rows.dedup_by(|a, b| a.0 == b.0);
        // An accessor declared in a test-only file (`test_only`) exists only in a test build.
        let (tests, content): (Vec<_>, Vec<_>) = rows
            .into_iter()
            .partition(|r| crate::generator_test_scope::test_only(&r.3));
        let emit =
            |out: &mut Output, rows: Vec<(String, String, String, String, u32, Option<String>)>| {
                for (name, system, var, rel, line, typed) in rows {
                    match &typed {
                        Some(t) => {
                            out.doc(format!("SYSTEM_ACCESSOR({}, {}, nameof({}), {}) at {}:{}: the {} system's `{}`, read as a typed var.", system, name, var, t, rel, line, system, var));
                            out.line(format!("/proc/{}() as {}", name, t));
                            out.line(format!("	RETURN_TYPE({})", t));
                        }
                        None => {
                            out.doc(format!("SYSTEM_ACCESSOR({}, {}, nameof({})) at {}:{}: the {} system's `{}`, read as a plain var.", system, name, var, rel, line, system, var));
                            out.line(format!("/proc/{}()", name));
                        }
                    }
                    out.line(format!("	return {}?.{}", instance(&system), var));
                    out.blank();
                }
            };
        emit(&mut out, content);
        if !tests.is_empty() {
            out.line(crate::generator_test_scope::TEST_GUARD);
            out.blank();
            emit(&mut out, tests);
            out.line("#endif");
        }
        out
    }
}
