//! Exact SYSTEM_ACCESSOR generator row policy shared by both source producers.
pub use crate::sparse_slots_policy::Diagnostic;
use std::collections::HashSet;
#[derive(Clone, Debug, Default, serde::Serialize)]
pub struct Output {
    pub body: String,
    pub diags: Vec<Diagnostic>,
    #[serde(skip)]
    budget: Option<std::sync::Arc<crate::captured_generator_budget::Budget>>,
}
impl PartialEq for Output {
    fn eq(&self, other: &Self) -> bool {
        self.body == other.body && self.diags == other.diags
    }
}
impl Eq for Output {}
impl Output {
    pub fn line(&mut self, s: impl AsRef<str>) {
        self.line_fmt(format_args!("{}", s.as_ref()));
    }
    pub fn line_fmt(&mut self, args: std::fmt::Arguments<'_>) {
        if let Some(budget) = &self.budget {
            if !budget.append_fmt(&mut self.body, args) {
                return;
            }
            budget.string(&mut self.body, "\n");
        } else {
            use std::fmt::Write;
            self.body.write_fmt(args).expect("String writer");
            self.body.push('\n');
        }
    }
    pub fn doc(&mut self, s: impl AsRef<str>) {
        self.doc_fmt(format_args!("{}", s.as_ref()));
    }
    pub fn doc_fmt(&mut self, args: std::fmt::Arguments<'_>) {
        self.line_fmt(format_args!("/// {}", args));
    }
    pub fn blank(&mut self) {
        self.line("");
    }
    pub fn diag(&mut self, rel: &str, line: u32, msg: impl std::fmt::Display) {
        self.diag_fmt(rel, line, format_args!("{}", msg));
    }
    pub fn diag_fmt(&mut self, rel: &str, line: u32, args: std::fmt::Arguments<'_>) {
        let (rel, msg) = if let Some(budget) = &self.budget {
            if self.diags.len() >= crate::captured_generator_budget::MAX_ROWS
                || !budget.row(&mut self.diags)
            {
                budget.deny();
                return;
            }
            let mut owned_rel = String::new();
            if !budget.string(&mut owned_rel, rel) {
                return;
            }
            let mut owned_msg = String::new();
            if !budget.append_fmt(&mut owned_msg, args) {
                return;
            }
            (owned_rel, owned_msg)
        } else {
            (rel.to_owned(), args.to_string())
        };
        self.diags.push(Diagnostic { rel, line, msg });
    }
    pub fn write_file_text(&self, out: &mut impl std::fmt::Write) -> std::fmt::Result {
        out.write_str("// GENERATED by tools/analyze: `analyze gen system_accessors`. Do not edit by hand; edit the declarations it reads.\n// Written to code/engine/_generated/system_accessors.dm; not committed: every build regenerates it (`analyze gen`).\n\n")?;
        out.write_str(&self.body)?;
        if !self.body.is_empty() && !self.body.ends_with('\n') {
            out.write_str("\n")?;
        }
        Ok(())
    }
    pub fn file_text(&self) -> String {
        let mut text = String::new();
        self.write_file_text(&mut text)
            .expect("String writer is infallible");
        text
    }
    pub fn captured_file_text(
        &self,
        budget: &crate::captured_generator_budget::Budget,
    ) -> Result<String, String> {
        let mut text = crate::captured_generator_budget::BudgetedText::new(budget);
        self.write_file_text(&mut text)
            .map_err(|_| "captured generator renderer allocation denied".to_owned())?;
        text.finish()
    }
}
pub fn system_types(system: &str) -> Vec<String> {
    vec![
        format!("/datum/world_service/{}", system),
        format!("/datum/system/{}", system),
    ]
}
pub fn visit_system_defs(
    raw: &str,
    mut visit: impl FnMut(&str) -> Result<(), String>,
) -> Result<(), String> {
    if raw.contains("SYSTEM_DEF(") {
        for c in crate::pat!(r"(?m)^\s*SYSTEM_DEF\((\w+)\)").captures_iter(raw) {
            visit(c.s(1))?;
        }
    }
    Ok(())
}
pub fn system_defs(raw: &str) -> Vec<String> {
    let mut defs = Vec::new();
    visit_system_defs(raw, |name| {
        defs.push(name.to_owned());
        Ok(())
    })
    .expect("infallible collector");
    defs
}
/// Exact file selection of sem::gen::system_vars, including prefix matches.
pub fn file_mentions_system(code: &str, system: &str) -> bool {
    let plain = !system.is_empty() && system.chars().all(|c| c.is_alphanumeric() || c == '_');
    if plain { file_mentions_system_with_types(code, system, &[]) }
    else { file_mentions_system_with_types(code, system, &system_types(system)) }
}
/// Same original candidate policy; callers may reuse the two original type names.
pub fn file_mentions_system_with_types(code:&str, system:&str, types:&[String])->bool {
    let plain = !system.is_empty() && system.chars().all(|c| c.is_alphanumeric() || c == '_');
    if !plain { return types.iter().any(|ty|code.contains(ty)); }
    for prefix in ["/datum/world_service/", "/datum/system/"] {
        let mut from = 0;
        while let Some(i) = code[from..].find(prefix) {
            let start = from + i + prefix.len();
            let end = code[start..].char_indices()
                .find(|(_,c)| !c.is_alphanumeric() && *c != '_')
                .map_or(code.len(), |(i,_)|start+i);
            if code[start..end].starts_with(system) { return true; }
            from = start;
        }
    }
    false
}

pub struct Builder {
    sys_defs: HashSet<String>,
    rows: Vec<(String, String, String, String, u32, Option<String>)>,
    out: Output,
}
impl Builder {
    pub(crate) fn captured(
        sys_defs: HashSet<String>,
        budget: std::sync::Arc<crate::captured_generator_budget::Budget>,
    ) -> Self {
        let mut out = Self::new(sys_defs);
        out.out.budget = Some(budget);
        out
    }

    pub fn new(sys_defs: HashSet<String>) -> Self {
        Self {
            sys_defs,
            rows: Vec::new(),
            out: Output::default(),
        }
    }
    pub fn push(
        &mut self,
        rel: &str,
        line: u32,
        args: &[String],
        has_var: impl Fn(&str, &str) -> bool,
    ) {
        let (Some(system), Some(name), Some(key)) = (args.first(), args.get(1), args.get(2)) else {
            self.out.diag(
                rel,
                line,
                "SYSTEM_ACCESSOR(system, name, nameof(var)) needs three arguments",
            );
            return;
        };
        let Some(var) = key
            .trim()
            .strip_prefix("nameof(")
            .and_then(|s| s.strip_suffix(')'))
            .map(|s| s.trim().to_string())
        else {
            self.out.diag(
                rel,
                line,
                format_args!(
                    "accessor `{}`: the third argument is nameof(var), not `{}`",
                    name, key
                ),
            );
            return;
        };
        if !has_var(system, &var) {
            self.out.diag_fmt(
                rel,
                line,
                format_args!(
                    "accessor `{}`: system `{}` has no var `{}` (looked at /datum/world_service/{}, /datum/system/{})",
                    name,
                    system,
                    var,
                    system, system
                ),
            );
            return;
        }
        let typed = match args.get(3).map(|t| t.trim().to_string()) {
            None => None,
            Some(t)
                if t.starts_with('/')
                    && t[1..]
                        .chars()
                        .all(|c| c.is_alphanumeric() || c == '_' || c == '/') =>
            {
                Some(t)
            }
            Some(t) => {
                self.out.diag_fmt(
                    rel,
                    line,
                    format_args!(
                        "accessor `{}`: the fourth argument is the var's type path, not `{}`",
                        name, t
                    ),
                );
                return;
            }
        };
        self.rows.push((
            name.clone(),
            system.clone(),
            var,
            rel.to_string(),
            line,
            typed,
        ));
    }
    pub fn finish(self) -> Output {
        let Self {
            sys_defs,
            mut rows,
            mut out,
        } = self;
        rows.sort();
        for w in rows.windows(2) {
            if w[0].0 == w[1].0 {
                out.diag_fmt(
                    &w[1].3,
                    w[1].4,
                    format_args!(
                        "accessor `{}` is declared twice (also {}:{})",
                        w[0].0, w[0].3, w[0].4
                    ),
                );
            }
        }
        rows.dedup_by(|a, b| a.0 == b.0);
        // An accessor declared in a test-only file (`test_only`) exists only in a test build.
        let (tests, content): (Vec<_>, Vec<_>) = rows
            .into_iter()
            .partition(|r| crate::generator_test_scope::test_only(&r.3));
        let emit =
            |out: &mut Output, rows: Vec<(String, String, String, String, u32, Option<String>)>| {
                for (name, system, var, rel, line, typed) in rows {
                    match &typed {
                        Some(t) => {
                            out.doc_fmt(format_args!("SYSTEM_ACCESSOR({}, {}, nameof({}), {}) at {}:{}: the {} system's `{}`, read as a typed var.", system, name, var, t, rel, line, system, var));
                            out.line_fmt(format_args!("/proc/{}() as {}", name, t));
                            out.line_fmt(format_args!("	RETURN_TYPE({})", t));
                        }
                        None => {
                            out.doc_fmt(format_args!("SYSTEM_ACCESSOR({}, {}, nameof({})) at {}:{}: the {} system's `{}`, read as a plain var.", system, name, var, rel, line, system, var));
                            out.line_fmt(format_args!("/proc/{}()", name));
                        }
                    }
                    let (prefix, suffix) = if sys_defs.contains(&system) {
                        ("SS", "")
                    } else {
                        ("GLOB.", "_service")
                    };
                    out.line_fmt(format_args!(
                        "\treturn {}{}{}?.{}",
                        prefix, system, suffix, var
                    ));
                    out.blank();
                }
            };
        emit(&mut out, content);
        if !tests.is_empty() {
            out.line(crate::generator_test_scope::TEST_GUARD);
            out.blank();
            emit(&mut out, tests);
            out.line("#endif");
        }
        out
    }
}

#[cfg(test)]
mod captured_writer_tests {
    use super::*;
    #[test]
    fn header_larger_than_empty_body_is_actual_bounded_output() {
        let out = Output::default();
        let expected = out.file_text();
        assert!(!expected.is_empty());
        let small = crate::captured_generator_budget::Budget::new(64).unwrap();
        assert!(out.captured_file_text(&small).is_err());
        let enough = crate::captured_generator_budget::Budget::new(4096).unwrap();
        assert_eq!(out.captured_file_text(&enough).unwrap(), expected);
    }
}

#[cfg(test)]
mod captured_format_tests {
    use super::*;
    #[test]
    fn formatted_padding_is_bounded_without_a_temporary_string() {
        let b = crate::captured_generator_budget::Budget::new(512).unwrap();
        let mut out = Output {
            budget: Some(b.clone()),
            ..Default::default()
        };
        out.doc_fmt(format_args!("{:>width$}", "x", width = 60_000));
        assert!(b.denied());
        assert!(out.body.capacity() <= 512);
        assert!(out.captured_file_text(&b).is_err());
    }
    #[test]
    fn diagnostic_format_denial_never_publishes_a_partial_message() {
        let b = crate::captured_generator_budget::Budget::new(2048).unwrap();
        let mut out = Output {
            budget: Some(b.clone()),
            ..Default::default()
        };
        out.diag_fmt(
            "code/a.dm",
            1,
            format_args!("{:>width$}", "x", width = 60_000),
        );
        assert!(b.denied());
        assert!(out.diags.is_empty());
    }
}
