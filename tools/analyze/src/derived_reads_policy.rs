//! Exact original derived/reaction read and boot templates. No source model.
use std::collections::{BTreeMap,BTreeSet};
pub(crate) type OwnerSlots=BTreeMap<String,BTreeMap<(String,String),Vec<String>>>;
pub(crate) type ReactionSlots=BTreeMap<String,BTreeMap<&'static str,Vec<String>>>;
pub(crate) fn boot_text(flags:&BTreeMap<String,BTreeSet<&'static str>>,members:&[String])->Vec<String>{
    let mut out: Vec<String> = Vec::new();
    let mut push = |s: &str| out.push(s.to_string());
    push("/// Types whose reactions() declare every() / on_cross() / on_notice(), with the RXB_* kinds (code/datums/reactions/work.dm).");
    push("/proc/rx_boot_types()");
    push("\tRETURN_TYPE(/list)");
    push("\t// Built on first call: a static or global initializer may not have run yet when the first atoms initialize.");
    push("\t// ALLOW(sys_static_getter): built on first call; a global list may not exist yet while the first atoms initialize");
    push("\tvar/static/list/table");
    push("\tif(!table)");
    if !flags.is_empty() {
        push("\t\ttable = list(");
        for (owner, fl) in flags {
            let joined = fl.iter().cloned().collect::<Vec<_>>().join(" | ");
            push(&format!("\t\t\t{} = {},", owner, joined));
        }
        push("\t\t)");
    } else {
        push("\t\ttable = list()");
    }
    push("\treturn table");
    push("");
    push("/// Capabilities some every(members = ...) runs per member of: their holders join the membership store at init.");
    push("/proc/rx_boot_members()");
    push("\tRETURN_TYPE(/list)");
    push("\t// ALLOW(sys_static_getter): built on first call; a global list may not exist yet while the first atoms initialize");
    push("\tvar/static/list/table");
    push("\tif(!table)");
    if !members.is_empty() {
        push("\t\ttable = list(");
        for cap in members {
            push(&format!("\t\t\t{},", cap));
        }
        push("\t\t)");
    } else {
        push("\t\ttable = list()");
    }
    push("\treturn table");
    push("");
    out
}

pub(crate) fn generate(per_owner:&OwnerSlots,reaction_slots:&ReactionSlots,flags:&BTreeMap<String,BTreeSet<&'static str>>,members:&[String],test_types:&BTreeSet<String>)->String{
    let mut out: Vec<String> = vec![
        "// GENERATED by tools/ci/derived_reads_lint.py --fix-generated. Do not edit by hand.".to_string(),
        "// What each type's should_run / draw / hidden_verbs / tgui_data / push_to_rust / derive_<x> read, as implicit".to_string(),
        "// reads for READERS() (code/datums/reactions). Not committed: every build regenerates it.".to_string(),
        String::new(),
    ];
    let owners: BTreeSet<&String> = per_owner.keys().chain(reaction_slots.keys()).collect();
    // Types that only the test fixtures define are compiled in test builds only: their reads go in a UNIT_TESTS block.
    let mut test_out: Vec<String> = Vec::new();
    for owner in owners {
        let test_owner = test_types.contains(owner.as_str());
        let mut lines: Vec<String> = Vec::new();
        if let Some(slots) = per_owner.get(owner) {
            for ((kind, value), names) in slots {
                if names.is_empty() {
                    continue;
                }
                let mut sorted = names.clone();
                sorted.sort();
                let args = sorted.iter().map(|n| format!("nameof({})", n)).collect::<Vec<_>>().join(", ");
                if kind == "derive" {
                    lines.push(format!("\t. += derive(nameof({}), {})", value, args));
                } else {
                    lines.push(format!("\t. += {}({})", kind_call(kind).unwrap_or(""), args));
                }
            }
        }
        if let Some(handlers) = reaction_slots.get(owner) {
            for (handler, reads) in handlers {
                if !reads.is_empty() {
                    let mut sorted = reads.clone();
                    sorted.sort();
                    lines.push(format!("\t. += reaction_reads(PROC_REF({}), {})", handler, sorted.join(", ")));
                }
            }
        }
        if !lines.is_empty() {
            let dest = if test_owner { &mut test_out } else { &mut out };
            dest.push(format!("{}/generated_reads()", owner));
            dest.push("\t. = ..()".to_string());
            dest.extend(lines);
            dest.push(String::new());
        }
    }
    if !test_out.is_empty() {
        out.push("#if defined(UNIT_TESTS) || defined(SPACEMAN_DMM)".to_string());
        out.extend(test_out);
        out.push("#endif".to_string());
        out.push(String::new());
    }
    out.extend(boot_text(flags,members));
    out.join("\n")
}
pub(crate) fn kind_call(kind: &str) -> Option<&'static str> {
    match kind {
        "runs" => Some("runs_while"),
        "drawn" => Some("drawn_from"),
        "ui" => Some("ui_from"),
        "push" => Some("rust_push"),
        _ => None,
    }
}

#[cfg(feature="native-policy")]
pub(crate) fn generate_admitted(per_owner:&OwnerSlots,reaction_slots:&ReactionSlots,flags:&BTreeMap<String,BTreeSet<&'static str>>,members:&[String],test_types:&BTreeSet<String>,budget:&std::sync::Arc<crate::captured_generator_budget::Budget>,checkpoint:&dyn Fn()->std::io::Result<()>)->std::io::Result<String>{
 checkpoint()?;let mut width=0usize;let mut units=64usize;let overflow=||{budget.deny();std::io::Error::new(std::io::ErrorKind::OutOfMemory,"derived read renderer input width overflow")};
 let mut add=|text:&str|->std::io::Result<()>{width=width.checked_add(text.len()).ok_or_else(&overflow)?;units=units.checked_add(1).ok_or_else(&overflow)?;Ok(())};
 for(owner,slots)in per_owner{checkpoint()?;add(owner)?;for((kind,value),names)in slots{add(kind)?;add(value)?;for name in names{add(name)?;}}}
 for(owner,slots)in reaction_slots{checkpoint()?;add(owner)?;for(handler,names)in slots{add(handler)?;for name in names{add(name)?;}}}
 for(owner,kinds)in flags{checkpoint()?;add(owner)?;for kind in kinds{add(kind)?;}}for member in members{add(member)?;}
 // Sorted cloned names, quoted line/join buffers, ordinary/test line vectors
 // and final join coexist.32x widths plus per-name nodes fund that unique old
 // renderer before it creates any new owned output. No source/model is kept.
 let reserve=width.checked_mul(32).and_then(|n|units.checked_mul(1024).and_then(|m|n.checked_add(m))).ok_or_else(&overflow)?;
 budget.charge(reserve).map_err(|message|std::io::Error::new(std::io::ErrorKind::OutOfMemory,message))?;
 let text=generate(per_owner,reaction_slots,flags,members,test_types);checkpoint()?;
 if budget.denied()||text.capacity()>reserve{budget.deny();return Err(std::io::Error::new(std::io::ErrorKind::OutOfMemory,"derived read renderer admission refused"))}Ok(text)
}

