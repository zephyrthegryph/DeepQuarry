#!/usr/bin/env python3
"""Writes code/modules/mob/living/life/life_dispatch.dm from life_steps.dm.

The Life sequence calls a mob's steps through /datum/sequence/life/run_step() and ask_step(), which call the switches this
writes: a typed call per step proc (virtual dispatch, ~1 us) instead of call(mob, "name") (a lookup in the mob type's proc
table, ~15-20 us on a human). A step the switch does not list still runs, by name. Re-run after adding or renaming a Life
step: python3 tools/dx/life_dispatch_gen.py
"""
import re
import subprocess

STEPS = 'code/modules/mob/living/life/life_steps.dm'
OUT = 'code/modules/mob/living/life/life_dispatch.dm'

text = open(STEPS, encoding='utf-8').read()
handlers, asks = [], []
for m in re.finditer(r'seq_step\(PROC_REF\((\w+)\)([^\n]*)', text):
    if m.group(1) not in handlers:
        handlers.append(m.group(1))
    for a in re.findall(r'(?:should_run|rewake) = PROC_REF\((\w+)\)', m.group(2)):
        if a not in asks:
            asks.append(a)


def defining_type(name):
    out = subprocess.run(['git', 'grep', '-h', '-E', rf'^/mob[A-Za-z0-9_/]*/proc/{name}\(', '--', '*.dm'],
                         capture_output=True, text=True).stdout
    types = [re.match(r'^(/mob[A-Za-z0-9_/]*?)/proc/', l).group(1) for l in out.split('\n') if l]
    if not types:
        raise SystemExit(f'no proc/ definition of {name}')
    return min(types, key=lambda t: t.count('/'))


def case(name, call_args):
    t = defining_type(name)
    if t == '/mob/living':
        return [f'\t\tif("{name}")', f'\t\t\treturn {name}({call_args})']
    return [f'\t\tif("{name}")', f'\t\t\tvar{t}/M = src', f'\t\t\treturn M.{name}({call_args})']


L = ['// GENERATED by tools/dx/life_dispatch_gen.py from life_steps.dm: re-run it after adding or renaming a Life step.',
     '// The Life sequence\'s typed step dispatch (/datum/sequence/life/run_step(), ask_step()): a by-name call() looks the',
     '// name up in the mob type\'s proc table on every call; these switches make one virtual call. An unlisted name still',
     '// runs, by name.',
     '',
     '/datum/sequence/life/run_step(mob/living/L, name, datum/seq_frame/life/F)',
     '\treturn L.life_step(name, F)',
     '',
     '/datum/sequence/life/ask_step(mob/living/L, name)',
     '\treturn L.life_step_ask(name)',
     '',
     '/// Runs Life step `name` with frame `F`.',
     '/mob/living/proc/life_step(name, datum/seq_frame/life/F)',
     '\tswitch(name)']
for h in handlers:
    L += case(h, 'F')
L += ['\treturn call(src, name)(F)', '',
      '/// A Life step\'s should_run or rewake proc `name`.',
      '/mob/living/proc/life_step_ask(name)',
      '\tswitch(name)']
for a in asks:
    L += case(a, '')
L += ['\treturn call(src, name)()', '']
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(L))
print(f'{len(handlers)} steps, {len(asks)} asks')
