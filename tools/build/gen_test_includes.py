#!/usr/bin/env python3
"""Writes the include lists of the test tree: code/tests/_tests.dm and the include block of code/tests/unit_tests/_unit_tests.dm.

    python3 tools/build/gen_test_includes.py            # write them (only when their text changes)
    python3 tools/build/gen_test_includes.py --check    # exit 1 when either is not what the tree and the spec give
    python3 tools/build/gen_test_includes.py --selftest

deepquarry.dme skips code/tests/** (tools/build/dme_spec.txt): the test tree is compiled last, behind `#if defined(UNIT_TESTS)`, from its
two aggregators. Their include lists are generated the same way the manifest is: every .dm file under code/tests is included, except the
aggregators themselves and the `exclude` lines of the spec (tools/build/test_includes_spec.txt), each with its reason. A test file that is
on disk is compiled; nothing has to remember to list it. gen_dme.py runs this whenever it runs (every build target that compiles or lints
DM), and its --check (tools/ci/check_ratchets.sh) checks this too.

Where each file goes:
    code/tests/unit_tests/** and code/tests/balance/**   the block between `// BEGIN_INCLUDE` and `// END_INCLUDE` of _unit_tests.dm
    a file an `in GUARD GLOB` line names                 that guard's `#if` block, after END_INCLUDE
    everything else under code/tests                     code/tests/_tests.dm

Order is pinned like the manifest's (gen_dme.pin): a file already listed keeps its slot, a new one goes after its path-order
predecessor, `first` and `before` rules (gen_dme syntax) order what the path order does not. The text of _unit_tests.dm before
`// BEGIN_INCLUDE` (the TEST_* macros) and from its closing `#undef` lines on is kept as written.

Spec lines (`#` starts a comment):
    exclude PATH                 never included from an aggregator (say why on the line)
    guard NAME CONDITION...      a block `#CONDITION` ... `#endif` (CONDITION is e.g. `if defined(BENCHMARK)` or `ifdef X`)
    in NAME GLOB                 the matches go in guard NAME's block
    first GLOB / before A B      ordering rules, as in dme_spec.txt
"""
from __future__ import annotations

import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_dme  # noqa: E402

ROOT = gen_dme.ROOT
SPEC = "tools/build/test_includes_spec.txt"
TESTS = "code/tests/_tests.dm"
UNIT = "code/tests/unit_tests/_unit_tests.dm"
REGEN = "python3 tools/build/gen_test_includes.py"
BEGIN = "// BEGIN_INCLUDE\n"
END = "// END_INCLUDE\n"

TESTS_HEADER = """\
// Cross-cutting test code, compiled only under UNIT_TESTS: GENERATED by tools/build/gen_test_includes.py (every .dm under code/tests that is
// not a unit test, a benchmark or a balance scenario; the driver first, see tools/build/test_includes_spec.txt). Do not edit the list by hand.
// The E0 proofs themselves are /datum/unit_test types under code/tests/unit_tests/ so the unit-test runner finds them like any other test.

#if defined(UNIT_TESTS) || defined(SPACEMAN_DMM)
"""
TESTS_FOOTER = "#endif\n"


class Spec:
    def __init__(self, text: str):
        self.exclude: set[str] = set()
        self.guards: list[tuple[str, str]] = []
        self.into: list[tuple[str, re.Pattern, str]] = []
        order_lines: list[str] = []
        self.rules: list[tuple[int, str, str]] = []
        for number, raw in enumerate(text.splitlines(), 1):
            line = re.split(r"(?:^|\s)#", raw, maxsplit=1)[0].strip()
            if not line:
                continue
            kind, _, rest = line.partition(" ")
            rest = rest.strip()
            if kind == "exclude":
                self.exclude.add(rest)
                self.rules.append((number, kind, rest))
            elif kind == "guard":
                name, _, cond = rest.partition(" ")
                self.guards.append((name, cond.strip()))
            elif kind == "in":
                name, _, g = rest.partition(" ")
                self.into.append((name, gen_dme.glob_re(g.strip()), g.strip()))
                self.rules.append((number, kind, g.strip()))
            elif kind in ("first", "before"):
                order_lines.append(line)
            else:
                raise gen_dme.SpecError(f"{SPEC}:{number}: unknown directive: {raw.strip()}")
        self.order = gen_dme.Spec("\n".join(order_lines), SPEC)

    def guard_of(self, path: str) -> str | None:
        for name, pattern, _ in self.into:
            if pattern.match(path):
                return name
        return None


def on_disk(root: str) -> list[str]:
    out = []
    for d, dirs, names in os.walk(os.path.join(root, "code", "tests")):
        dirs.sort()
        for n in names:
            if n.endswith(".dm"):
                out.append(os.path.relpath(os.path.join(d, n), root).replace("\\", "/"))
    return sorted(out, key=gen_dme.path_key)


def listed(root: str, agg: str) -> list[str]:
    try:
        with open(os.path.join(root, agg), encoding="utf-8", errors="replace", newline="") as fh:
            text = fh.read()
    except FileNotFoundError:
        return []
    base = os.path.dirname(agg)
    return [os.path.normpath(os.path.join(base, p.replace("\\", "/"))).replace("\\", "/") for p in gen_dme.INCLUDE.findall(text)]


def rel(agg: str, path: str, sep: str) -> str:
    return os.path.relpath(path, os.path.dirname(agg)).replace("\\", "/").replace("/", sep)


def generate(root: str = ROOT, spec_text: str | None = None) -> dict[str, str]:
    if spec_text is None:
        with open(os.path.join(root, SPEC), encoding="utf-8") as fh:
            spec_text = fh.read()
    spec = Spec(spec_text)
    files = [f for f in on_disk(root) if f not in (TESTS, UNIT) and f not in spec.exclude]
    stale = [f"{SPEC}:{n}: `{k} {g}` matches no file" for n, k, g in spec.rules
             if not any(gen_dme.glob_re(g).match(f) for f in on_disk(root))]
    if stale:
        raise gen_dme.SpecError("a stale rule (drop or update it):\n  " + "\n  ".join(stale))
    recorded = listed(root, TESTS) + listed(root, UNIT)
    ordered = gen_dme.order(spec.order, files, None, recorded)
    tests, unit, guarded = [], [], {name: [] for name, _ in spec.guards}
    for f in ordered:
        g = spec.guard_of(f)
        if g is not None:
            if g not in guarded:
                raise gen_dme.SpecError(f"{SPEC}: `in {g}` names no guard")
            guarded[g].append(f)
        elif f.startswith(("code/tests/unit_tests/", "code/tests/balance/")):
            unit.append(f)
        else:
            tests.append(f)

    out = {TESTS: TESTS_HEADER + "".join(f'#include "{rel(TESTS, f, chr(92))}"\n' for f in tests) + TESTS_FOOTER}
    with open(os.path.join(root, UNIT), encoding="utf-8", errors="replace", newline="") as fh:
        text = fh.read().replace("\r\n", "\n")
    if BEGIN not in text:
        raise gen_dme.SpecError(f"{UNIT} has no `{BEGIN.strip()}` line")
    head = text[:text.index(BEGIN) + len(BEGIN)]
    after = text[text.index(BEGIN):]
    m = re.search(r"^#undef ", after, re.M)
    if not m:
        raise gen_dme.SpecError(f"{UNIT} has no closing #undef lines after the include block")
    tail = after[m.start():]
    body = ["".join(f'#include "{rel(UNIT, f, "/")}"\n' for f in unit), END]
    for name, cond in spec.guards:
        if guarded[name]:
            body.append(f"\n#{cond}\n" + "".join(f'#include "{rel(UNIT, f, "/")}"\n' for f in guarded[name]) + "#endif\n")
    out[UNIT] = head + "".join(body) + "\n" + tail
    return out


def main(argv: list[str]) -> int:
    if "--selftest" in argv:
        return selftest()
    root = ROOT
    if "--root" in argv:
        root = os.path.abspath(argv[argv.index("--root") + 1])
    try:
        texts = generate(root)
    except gen_dme.SpecError as e:
        print(f"gen_test_includes: {e}", file=sys.stderr)
        return 2
    bad = 0
    for path, text in texts.items():
        full = os.path.join(root, path)
        try:
            with open(full, encoding="utf-8", errors="replace", newline="") as fh:
                current = fh.read()
        except FileNotFoundError:
            current = None
        if current == text:
            continue
        if "--check" in argv:
            old, new = set(listed(root, path)), set(gen_dme.INCLUDE.findall(text))
            new = {os.path.normpath(os.path.join(os.path.dirname(path), p.replace("\\", "/"))).replace("\\", "/") for p in new}
            print(f"gen_test_includes: {path} is stale (regenerate: {REGEN}).", file=sys.stderr)
            for p in sorted(new - old)[:20]:
                print(f"  missing  {p}", file=sys.stderr)
            for p in sorted(old - new)[:20]:
                print(f"  extra    {p}", file=sys.stderr)
            bad = 1
            continue
        with open(full, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        print(f"gen_test_includes: wrote {path} ({text.count(chr(10) + '#include') + text.startswith('#include')} includes)")
    return bad


def selftest() -> int:
    import tempfile
    fails = 0

    def check(name: str, cond: bool) -> None:
        nonlocal fails
        print(("ok   " if cond else "FAIL ") + name)
        fails += 0 if cond else 1

    with tempfile.TemporaryDirectory() as root:
        def put(p: str, text: str = "") -> None:
            os.makedirs(os.path.dirname(os.path.join(root, p)), exist_ok=True)
            with open(os.path.join(root, p), "w", encoding="utf-8", newline="\n") as fh:
                fh.write(text)
        put(UNIT, "#define TEST_ASSERT(x) x\n" + BEGIN + '#include "b.dm"\n#include "a.dm"\n' + END + "#undef TEST_ASSERT\n#endif\n")
        put(TESTS, '#include "driver\\driver.dm"\n')
        for p in ("unit_tests/a.dm", "unit_tests/b.dm", "unit_tests/c.dm", "unit_tests/sub/d.dm", "driver/driver.dm", "driver/aaa.dm",
                  "engine/x.dm", "benchmarks/_b.dm", "unit_tests/skip.dm"):
            put("code/tests/" + p)
        spec = ("exclude code/tests/unit_tests/skip.dm  # test\nguard bench if defined(BENCHMARK)\nin bench code/tests/benchmarks/**\n"
                "first code/tests/driver/driver.dm\n")
        texts = generate(root, spec)
        u = texts[UNIT]
        check("recorded order kept, a new file after its path-order predecessor", u.index('"b.dm"') < u.index('"c.dm"') < u.index('"a.dm"'))
        check("subdirectories are included", '#include "sub/d.dm"' in u)
        check("an excluded file is not included", "skip.dm" not in u)
        check("a guarded file goes in its block after END_INCLUDE",
              u.index(END) < u.index("#if defined(BENCHMARK)\n#include \"../benchmarks/_b.dm\"\n#endif"))
        check("head and closing #undef kept", u.startswith("#define TEST_ASSERT(x) x\n" + BEGIN) and u.endswith("#undef TEST_ASSERT\n#endif\n"))
        t = texts[TESTS]
        check("_tests.dm: driver first, the rest in path order",
              t.index("driver\\driver.dm") < t.index("driver\\aaa.dm") < t.index("engine\\x.dm") and '"unit_tests' not in t)
        try:
            generate(root, spec + "exclude code/tests/gone.dm # x\n")
            check("a stale exclude fails", False)
        except gen_dme.SpecError:
            check("a stale exclude fails", True)
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
