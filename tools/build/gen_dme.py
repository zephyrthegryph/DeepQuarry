#!/usr/bin/env python3
"""Writes deepquarry.dme from the files on disk and a small ordering spec (tools/build/dme_spec.txt).

    python3 tools/build/gen_dme.py              # write deepquarry.dme (only when its text changes)
    python3 tools/build/gen_dme.py --check      # exit 1 when deepquarry.dme is not what the spec and the tree give
    python3 tools/build/gen_dme.py --out FILE   # write the generated manifest somewhere else (the order-equivalence check)
    python3 tools/build/gen_dme.py --selftest   # the generator's own tests

The include list is never edited by hand: add, move or delete a .dm file and run the build (every target that compiles or lints DM
regenerates it first), or run this script. What genuinely depends on include order is an explicit rule in the spec, each with the
reason, found by compiling the generated order against the old hand order and comparing the worlds with dmb-equiv
(tools/ci/dme_order_equiv.sh). Everything else is in path order.

The spec (one directive per line, `#` comments; paths use `/`, globs `*` (one segment) and `**` (any depth)):

    scan DIR                 every .dm file under DIR (recursive) is included
    file PATH                include PATH even when it is not on disk (a generated file)
    skip GLOB                files under a scanned root that are not included directly (an aggregator includes them, or a generator
                             writes them and a `file` line places them)
    first GLOB               the matches go first, in the order of the `first` lines (path order within one line)
    last GLOB                the matches go last, in the order of the `last` lines
    before GLOB_A GLOB_B     every match of A is included before every match of B (a dependency the path order does not give)
    ifdef NAME PATH          `#ifdef NAME` / `#include PATH` / `#endif` before the `last` group (an optional, generated file)
    optional PATH            include PATH when it is on disk (a file a `skip` would drop, or one a queued lane adds)

The header (genesis call, FILE_DIR) is fixed text below.
"""
from __future__ import annotations

import os
import re
import sys
import functools
import heapq

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
SPEC = "tools/build/dme_spec.txt"
INCLUDE = re.compile(r'^[ \t]*#include\s+"([^"]+)"', re.M)
DME = "deepquarry.dme"
REGEN = "python3 tools/build/gen_dme.py"

HEADER = """\
// deepquarry.dme: GENERATED by tools/build/gen_dme.py from the files on disk and tools/build/dme_spec.txt. Do not edit the include
// list by hand: add, move or delete .dm files and run the build, or `python3 tools/build/gen_dme.py`. An include whose position
// matters is a rule in the spec, with its reason.

// This should always be the VERY FIRST THING: code/genesis_call.dme says why. No other #include may precede it.
#include "code\\genesis_call.dme"

// BEGIN_INTERNALS
// END_INTERNALS

// BEGIN_FILE_DIR
// Explicit per-tree resource paths (`#define FILE_DIR .` made DreamMaker scan every subdirectory). icons/gen (built from the PNG +
// .dmi.toml sources by tools/dq_icons/build_step.py) comes first so the generated DMIs shadow the committed .dmi tree.
#define FILE_DIR icons/gen
#define FILE_DIR icons
#define FILE_DIR sound
#define FILE_DIR maps
#define FILE_DIR interface
#define FILE_DIR html
#define FILE_DIR strings
#define FILE_DIR config
// END_FILE_DIR

// BEGIN_PREFERENCES
// END_PREFERENCES

// BEGIN_INCLUDE
"""

FOOTER = "// END_INCLUDE\n"


class SpecError(Exception):
    pass


@functools.lru_cache(maxsize=None)
def glob_re(pattern: str) -> re.Pattern:
    """`*` is one path segment's characters, `**` any depth (also none), `?` one character; a pattern naming a directory matches its files."""
    out = []
    i = 0
    while i < len(pattern):
        c = pattern[i]
        if pattern.startswith("**/", i):
            out.append("(?:.*/)?")
            i += 3
            continue
        if pattern.startswith("**", i):
            out.append(".*")
            i += 2
            continue
        if c == "*":
            out.append("[^/]*")
        elif c == "?":
            out.append("[^/]")
        else:
            out.append(re.escape(c))
        i += 1
    body = "".join(out)
    return re.compile("(?i)^" + body + "(?:/.*)?$")


class Spec:
    def __init__(self, text: str, where: str = SPEC):
        self.scan: list[str] = []
        self.files: list[str] = []
        self.optional: list[str] = []
        self.skip: list[re.Pattern] = []
        self.first: list[re.Pattern] = []
        self.last: list[re.Pattern] = []
        self.before: list[tuple[re.Pattern, re.Pattern, str]] = []
        self.ifdef: list[tuple[str, str]] = []
        self.macro_ignore: set[str] = set()
        self.patterns: list[tuple[str, int, str]] = []  # (directive, line, glob): each must match something
        self.scanned: set[str] = set()  # every .dm file under a scan root, before the skips
        for number, raw in enumerate(text.splitlines(), 1):
            line = raw.split("#", 1)[0].strip()
            if not line:
                continue
            words = line.split()
            kind, args = words[0], words[1:]
            want = {"scan": 1, "file": 1, "skip": 1, "first": 1, "last": 1, "before": 2, "ifdef": 2, "macro-ignore": 1, "optional": 1}
            if kind not in want or len(args) != want[kind]:
                raise SpecError(f"{where}:{number}: expected one of {', '.join(f'{k} ({v} argument(s))' for k, v in want.items())}: {raw.strip()}")
            if kind == "scan":
                self.scan.append(args[0].rstrip("/"))
            elif kind == "file":
                self.files.append(args[0])
            elif kind == "optional":
                self.optional.append(args[0])
            elif kind == "skip":
                self.skip.append(glob_re(args[0]))
            elif kind == "first":
                self.first.append(glob_re(args[0]))
            elif kind == "last":
                self.last.append(glob_re(args[0]))
            elif kind == "before":
                self.before.append((glob_re(args[0]), glob_re(args[1]), f"{where}:{number}"))
            elif kind == "ifdef":
                self.ifdef.append((args[0], args[1]))
            elif kind == "macro-ignore":
                self.macro_ignore.add(args[0])
            if kind in ("skip", "first", "last"):
                self.patterns.append((kind, number, args[0]))
            if kind == "before":
                self.patterns.append((kind, number, args[0]))
                self.patterns.append((kind, number, args[1]))


def path_key(path: str) -> tuple:
    """Path order: by segment, case-insensitive, a directory's files before its subdirectories."""
    parts = path.lower().split("/")
    return tuple((1, p) for p in parts[:-1]) + ((0, parts[-1]),)


def ignored_files(root: str, roots: list[str]) -> set[str]:
    """Files git ignores under the scan roots (build output: the analyzer's and the Verdigris generated DM). They are included only
    when a `file` line names them, so a stray generated file never joins the manifest. Outside a git work tree: none."""
    import subprocess

    try:
        out = subprocess.run(["git", "-C", root, "ls-files", "--others", "--ignored", "--exclude-standard", "--", *roots],
                             capture_output=True, text=True, timeout=60)
    except (OSError, subprocess.SubprocessError):
        return set()
    if out.returncode != 0:
        return set()
    return {line.strip() for line in out.stdout.splitlines() if line.strip()}


def collect(spec: Spec, root: str) -> list[str]:
    found: set[str] = set()
    ignored = ignored_files(root, spec.scan) if os.path.isdir(os.path.join(root, ".git")) or os.path.isfile(os.path.join(root, ".git")) else set()
    for base in spec.scan:
        top = os.path.join(root, base)
        if not os.path.isdir(top):
            raise SpecError(f"scan {base}: no such directory")
        for dirpath, dirnames, filenames in os.walk(top):
            dirnames.sort()
            for name in filenames:
                if not name.endswith(".dm"):
                    continue
                rel = os.path.relpath(os.path.join(dirpath, name), root).replace("\\", "/")
                spec.scanned.add(rel)
                if rel in ignored or any(p.match(rel) for p in spec.skip):
                    continue
                found.add(rel)
    for f in spec.files:
        found.add(f)
    for f in spec.optional:
        if os.path.isfile(os.path.join(root, f)):
            found.add(f)
    # A file another included file #includes (an aggregator: code/modules/tgs/includes.dm, maps/~turfpacks/turfpacks.dm) is the
    # aggregator's, not the manifest's: drop everything reachable from the scanned files' own includes. A `file` entry's includes are
    # not followed: the test aggregators include game files under UNIT_TESTS only (code/content/medical/_defines.dm), which the game
    # build still needs directly; their own trees are `skip` rules.
    owned: set[str] = set()
    queue = [f for f in found if f.endswith(".dm") and f not in spec.files and f not in spec.optional]
    seen: set[str] = set()
    while queue:
        f = queue.pop()
        if f in seen:
            continue
        seen.add(f)
        path = os.path.join(root, f)
        if not os.path.isfile(path):
            continue
        with open(path, encoding="utf-8", errors="replace") as fh:
            text = fh.read()
        if "#include" not in text:
            continue
        for raw in INCLUDE.findall(text):
            target = os.path.normpath(os.path.join(os.path.dirname(f), raw.replace("\\", "/"))).replace("\\", "/")
            if target != f:
                owned.add(target)
                queue.append(target)
    found -= owned - set(spec.files) - set(spec.optional)
    return sorted(found, key=path_key)


DEFINE = re.compile(r"^[ \t]*#[ \t]*define[ \t]+([A-Za-z_]\w*)(\()?", re.M)
UNDEF = re.compile(r"^[ \t]*#[ \t]*undef[ \t]+([A-Za-z_]\w*)", re.M)
TOKEN = re.compile(r"[A-Za-z_]\w*")
CALL = re.compile(r"([A-Za-z_]\w*)\s*\(")
# Comments and string/text literals (a name inside them is not a use). Rough on purpose: a `//` inside a string ends the line early,
# which can only lose a use, and a lost use only loses an ordering edge the equivalence check would show.
NOISE = re.compile(r'/\*.*?\*/|//[^\n]*|\{".*?"\}|"(?:\\.|[^"\\\n])*"', re.S)
# A #define's own body (with its continuation lines) is not a use: a macro is expanded where the outer macro is used, not where it is
# defined, so macros may name each other in any order.
DEFINE_BODY = re.compile(r"^[ \t]*#[ \t]*define\b(?:[^\n]*\\\n)*[^\n]*", re.M)


def unit_texts(root: str, files: list[str]) -> dict[str, str]:
    """Each manifest entry's text with everything it #includes (an aggregator's files count where the aggregator is)."""
    out: dict[str, str] = {}
    for f in files:
        parts: list[str] = []
        stack, seen = [f], set()
        while stack:
            g = stack.pop()
            if g in seen or not g.endswith(".dm"):
                continue
            seen.add(g)
            try:
                with open(os.path.join(root, g), encoding="utf-8", errors="replace") as fh:
                    text = fh.read()
            except OSError:
                continue
            parts.append(text)
            if "#include" in text:
                for raw in INCLUDE.findall(text):
                    stack.append(os.path.normpath(os.path.join(os.path.dirname(g), raw.replace("\\", "/"))).replace("\\", "/"))
        out[f] = "\n".join(parts)
    return out


def macro_violations(spec: Spec, root: str, ordered: list[str]) -> list[str]:
    """Uses of a macro before any #define of it, in the manifest's order: `file uses NAME, #defined later in other_file`. A file that
    #defines a macro and does not #undef it again exports it; a use is the name as a token outside comments and strings in another
    file (an aggregator's files count where the aggregator is) that does not #define it itself. Such a use compiles to other code (or
    fails) than the author meant, so the spec needs a rule that puts the definer first. `macro-ignore NAME` drops a name that is a
    macro in one file and an ordinary identifier elsewhere."""
    texts = unit_texts(root, ordered)
    pos = {f: i for i, f in enumerate(ordered)}
    exported: dict[str, list[str]] = {}
    own: dict[str, set[str]] = {}
    function_like: set[str] = set()
    undefined_by: dict[str, list[str]] = {}
    for f, text in texts.items():
        if "def" not in text:  # #define or #undef
            continue
        found = DEFINE.findall(text)
        defined = {name for name, _ in found}
        own[f] = defined
        local = set(UNDEF.findall(text))
        for name in local - defined:
            undefined_by.setdefault(name, []).append(f)
        for name, paren in found:
            if name not in local and name not in spec.macro_ignore:
                exported.setdefault(name, []).append(f)
                if paren:
                    function_like.add(name)
    names = set(exported)
    out: list[str] = []
    for f, text in texts.items():
        code = NOISE.sub(" ", DEFINE_BODY.sub(" ", text))
        # A function-like macro is expanded only where its name is followed by `(`: elsewhere the name is an ordinary identifier.
        used = {n for n in set(TOKEN.findall(code)) & names if n not in function_like} | (set(CALL.findall(code)) & function_like)
        for name in sorted(used):
            if name in own.get(f, ()):
                continue
            definers = exported[name]
            if all(pos[d] > pos[f] for d in set(definers)):
                out.append(f"{f} uses {name}, #defined later in {', '.join(sorted(definers))}")
                continue
            # A module's closing file (`~defines.dm`) #undefs the module's macros: a use after it, with no #define in between, is a
            # use of an undefined name.
            last_define = max((pos[d] for d in definers if pos[d] < pos[f]), default=-1)
            for x in undefined_by.get(name, ()):
                if last_define < pos[x] < pos[f]:
                    out.append(f"{f} uses {name} after {x} #undefs it")
    return sorted(out)


def order(spec: Spec, files: list[str], root: str | None = None) -> list[str]:
    """The `first` groups, then the rest in path order, then the `last` groups; then the `before` rules applied as a stable topological
    sort: a file moves only as far as a rule needs, everything else keeps its place."""
    placed: set[str] = set()
    head: list[str] = []
    for pattern in spec.first:
        for f in files:
            if f not in placed and pattern.match(f):
                head.append(f)
                placed.add(f)
    tail: list[str] = []
    for pattern in spec.last:
        for f in files:
            if f not in placed and pattern.match(f):
                tail.append(f)
                placed.add(f)
    base = head + [f for f in files if f not in placed] + tail
    rank = {f: i for i, f in enumerate(base)}
    preds: dict[str, set[str]] = {f: set() for f in base}
    why: dict[tuple[str, str], str] = {}
    for a, b, where in spec.before:
        As = [f for f in base if a.match(f)]
        Bs = [f for f in base if b.match(f)]
        for y in Bs:
            for x in As:
                if x == y:
                    continue  # `before A dir/**` where A is in dir: A before the rest of its directory
                preds[y].add(x)
                why[(x, y)] = where
    succ: dict[str, list[str]] = {f: [] for f in base}
    indeg = {f: len(p) for f, p in preds.items()}
    for y, ps in preds.items():
        for x in ps:
            succ[x].append(y)
    heap = [(rank[f], f) for f in base if indeg[f] == 0]
    heapq.heapify(heap)
    out: list[str] = []
    while heap:
        _, f = heapq.heappop(heap)
        out.append(f)
        for y in succ[f]:
            indeg[y] -= 1
            if indeg[y] == 0:
                heapq.heappush(heap, (rank[y], y))
    if len(out) != len(base):
        stuck = {f for f in base if indeg[f] > 0}
        cycle = [f"{x} -> {y} ({why.get((x, y), '?')})" for y in sorted(stuck) for x in sorted(preds[y]) if x in stuck][:12]
        raise SpecError("the `before` rules form a cycle:\n  " + "\n  ".join(cycle))
    return out


def render(spec: Spec, ordered: list[str]) -> str:
    def inc(p: str) -> str:
        return '#include "' + p.replace("/", "\\") + '"\n'

    out = [HEADER]
    ifdefs = [f"#ifdef {name}\n{inc(p)}#endif\n" for name, p in spec.ifdef]
    for p in ordered:
        if ifdefs and any(pat.match(p) for pat in spec.last):
            out += ifdefs
            ifdefs = []
        out.append(inc(p))
    out += ifdefs
    out.append(FOOTER)
    return "".join(out)


def generate(root: str = ROOT, spec_text: str | None = None) -> str:
    if spec_text is None:
        with open(os.path.join(root, SPEC), encoding="utf-8") as fh:
            spec_text = fh.read()
    spec = Spec(spec_text)
    files = collect(spec, root)
    ordered = order(spec, files, root)

    def matches(kind: str, g: str) -> bool:
        pool = spec.scanned if kind == "skip" else files
        pattern = glob_re(g)
        if any(pattern.match(f) for f in spec.optional):
            return True  # a rule for an `optional` file holds while the file is absent
        return any(pattern.match(f) for f in pool)

    unused = [f"{SPEC}:{n}: `{k} {g}` matches no file" for k, n, g in spec.patterns if not matches(k, g)]
    if unused:
        raise SpecError("a stale rule (the files it orders are gone; drop or update it):\n  " + "\n  ".join(unused))
    return render(spec, ordered)


def includes_of(text: str) -> set[str]:
    return {p.replace("\\", "/") for p in INCLUDE.findall(text)}


def merge(base: str, ours: str, theirs: str, root: str = ROOT, spec_text: str | None = None) -> str:
    """The merge of three versions of the manifest (the git merge driver, tools/build/dme_merge_driver.sh): an include is kept when both
    sides have it or one side added it (not in the base), and dropped when either side removed it; the result is ordered by the spec.
    Each side's include list is the file set of its tree, so this is what regenerating over the merged tree gives, without the tree
    (git runs the driver before it writes the merge out). A side whose manifest was hand-edited (a lane from before the generator)
    merges the same way; the merge tools regenerate from disk afterwards anyway."""
    if spec_text is None:
        with open(os.path.join(root, SPEC), encoding="utf-8") as fh:
            spec_text = fh.read()
    spec = Spec(spec_text)
    b, o, t = includes_of(base), includes_of(ours), includes_of(theirs)
    kept = (o & t) | (o - b) | (t - b)
    kept -= (b - o) | (b - t)
    kept |= set(spec.files)
    kept -= {p for _, p in spec.ifdef}
    kept.discard("code/genesis_call.dme")
    files = sorted(kept, key=path_key)
    return render(spec, order(spec, files, root))


def main(argv: list[str]) -> int:
    if "--selftest" in argv:
        return selftest()
    if "--merge" in argv:
        i = argv.index("--merge")
        base_p, ours_p, theirs_p = argv[i + 1:i + 4]
        texts = []
        for p in (base_p, ours_p, theirs_p):
            with open(p, encoding="utf-8", errors="replace", newline="") as fh:
                texts.append(fh.read())
        try:
            text = merge(*texts)
        except SpecError as e:
            print(f"gen_dme --merge: {e}", file=sys.stderr)
            return 2
        with open(ours_p, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        return 0
    root = ROOT
    if "--root" in argv:
        root = os.path.abspath(argv[argv.index("--root") + 1])  # another tree (a merged tree extracted by tools/ci/test_dme_merge.sh)
    out_path = os.path.join(root, DME)
    if "--out" in argv:
        out_path = os.path.abspath(argv[argv.index("--out") + 1])
    try:
        text = generate(root)
    except SpecError as e:
        print(f"gen_dme: {e}", file=sys.stderr)
        return 2
    try:
        with open(out_path, encoding="utf-8", newline="") as fh:
            current = fh.read()
    except FileNotFoundError:
        current = None
    if "--check" in argv or "--check-macros" in argv:
        spec = Spec(open(os.path.join(root, SPEC), encoding="utf-8").read())
        ordered = [p.replace("\\", "/") for p in INCLUDE.findall(text)]
        bad = macro_violations(spec, root, ordered)
        for line in bad:
            print(f"gen_dme: macro used before its #define: {line}", file=sys.stderr)
        if bad:
            print(f"gen_dme: {len(bad)} macro use(s) before the #define: add a `first`/`before` rule to {SPEC} (or `macro-ignore NAME`)",
                  file=sys.stderr)
        if "--check-macros" in argv:
            return 1 if bad else 0
        if current == text and not bad:
            return 0
        if current == text:
            return 1
        old = set(re.findall(r'^#include "([^"]+)"', current or "", re.M))
        new = set(re.findall(r'^#include "([^"]+)"', text, re.M))
        print(f"gen_dme: {DME} is stale (regenerate: {REGEN}).", file=sys.stderr)
        for p in sorted(new - old)[:20]:
            print(f"  missing  {p}", file=sys.stderr)
        for p in sorted(old - new)[:20]:
            print(f"  extra    {p}", file=sys.stderr)
        if old == new:
            print("  (same files, other order or header)", file=sys.stderr)
        return 1
    if current != text:
        with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        print(f"gen_dme: wrote {os.path.relpath(out_path, ROOT)} ({text.count(chr(10) + '#include')} includes)")
    return 0


def selftest() -> int:
    import tempfile

    failures = []

    def check(cond: bool, what: str) -> None:
        if not cond:
            failures.append(what)

    with tempfile.TemporaryDirectory() as tmp:
        def touch(rel: str) -> None:
            p = os.path.join(tmp, rel)
            os.makedirs(os.path.dirname(p), exist_ok=True)
            open(p, "w").close()

        for rel in ["code/__defines/b.dm", "code/__defines/a.dm", "code/game/z.dm", "code/game/A.dm", "code/game/sub/x.dm",
                    "code/tests/_tests.dm", "code/tests/t1.dm", "code/zz/over.dm", "code/mid/needs.dm", "code/aa/dep.dm"]:
            touch(rel)
        spec = """
scan code
skip code/tests/**
file code/tests/_tests.dm
file code/engine/_generated/gen.dm
first code/__defines/b.dm
first code/__defines/**
last code/engine/_generated/gen.dm
last code/zz/over.dm
before code/mid/needs.dm code/aa/dep.dm   # needs a macro of... (test)
ifdef DOC code/doc.dm
"""
        text = generate(tmp, spec)
        incs = re.findall(r'^#include "([^"]+)"', text, re.M)
        check(incs[0] == "code\\genesis_call.dme", "genesis first")
        body = incs[1:]
        check(body[:2] == ["code\\__defines\\b.dm", "code\\__defines\\a.dm"], f"first groups in rule order: {body[:2]}")
        check(body[-2:] == ["code\\engine\\_generated\\gen.dm", "code\\zz\\over.dm"], f"last groups in rule order: {body[-2:]}")
        check(body.index("code\\mid\\needs.dm") < body.index("code\\aa\\dep.dm"), "before rule holds")
        check(body.index("code\\game\\A.dm") < body.index("code\\game\\z.dm") < body.index("code\\game\\sub\\x.dm"),
              "path order: case-insensitive, files before subdirectories")
        check("code\\tests\\t1.dm" not in body and "code\\tests\\_tests.dm" in body, "skip drops the aggregated files, file keeps the aggregator")
        check(text.index("#ifdef DOC") < text.index("code\\engine\\_generated\\gen.dm"), "ifdef before the last group")
        try:
            generate(tmp, spec + "first code/gone/**\n")
            check(False, "a rule that matches nothing is refused")
        except SpecError:
            pass
        try:
            generate(tmp, "scan code\nbefore code/aa/dep.dm code/mid/needs.dm\nbefore code/mid/needs.dm code/aa/**\n")
            check(False, "a cycle is refused")
        except SpecError:
            pass
        check(generate(tmp, spec) == text, "deterministic")
        # optional: absent, its rule holds and nothing is included; present, it is included where its rule puts it.
        opt = spec + "skip code/zz/late.dm\noptional code/zz/late.dm\nlast code/zz/late.dm\n"
        check("late.dm" not in generate(tmp, opt), "an absent optional file is not included")
        touch("code/zz/late.dm")
        incs = re.findall(r'^#include "([^"]+)"', generate(tmp, opt), re.M)
        check(incs[-1] == "code\\zz\\late.dm", f"a present optional file goes where its rule puts it: {incs[-3:]}")
        # The macro check: a use before the #define (outside #define bodies, strings and comments) is reported, a function-like
        # macro's bare name is not a use, and a module's #undef file ends the macro.
        with open(os.path.join(tmp, "code/aa/dep.dm"), "w") as fh:
            fh.write("#define DEP_VALUE 3\n#define DEP_CALL(x) (x)\n")
        with open(os.path.join(tmp, "code/game/A.dm"), "w") as fh:
            fh.write("/proc/a()\n\treturn DEP_VALUE // DEP_CALL\n/proc/b(DEP_CALL)\n\treturn \"DEP_VALUE\"\n")
        with open(os.path.join(tmp, "code/game/z.dm"), "w") as fh:
            fh.write("#undef DEP_VALUE\n")
        with open(os.path.join(tmp, "code/game/sub/x.dm"), "w") as fh:
            fh.write("/proc/x()\n\treturn DEP_VALUE\n")
        sp = Spec("scan code\n")
        bad = macro_violations(sp, tmp, ["code/aa/dep.dm", "code/game/A.dm", "code/game/z.dm", "code/game/sub/x.dm"])
        check(bad == ["code/game/sub/x.dm uses DEP_VALUE after code/game/z.dm #undefs it"], f"undef scope: {bad}")
        bad = macro_violations(sp, tmp, ["code/game/A.dm", "code/aa/dep.dm", "code/game/z.dm"])
        check(bad == ["code/game/A.dm uses DEP_VALUE, #defined later in code/aa/dep.dm"], f"use before define, bare fn-macro name ignored: {bad}")
        # The merge driver: a hand-edited side (a lane from before the generator) adds one file and drops another; the generated side
        # added its own. The result has both additions, neither removed file, in spec order.
        base = '#include "code\\game\\A.dm"\n#include "code\\game\\z.dm"\n#include "code\\aa\\dep.dm"\n'
        ours = text.replace('#include "code\\game\\z.dm"\n', "")  # ours deleted z.dm
        theirs = base + '#include "code\\new\\lane.dm"\n'  # theirs added lane.dm, by hand, at the end
        theirs = theirs.replace('#include "code\\aa\\dep.dm"\n', "")  # and deleted dep.dm
        merged = re.findall(r'^#include "([^"]+)"', merge(base, ours, theirs, tmp, spec), re.M)
        check("code\\new\\lane.dm" in merged, "a side's addition is kept")
        check("code\\game\\z.dm" not in merged and "code\\aa\\dep.dm" not in merged, "a side's removal is kept")
        check("code\\game\\sub\\x.dm" in merged, "what ours added since the base is kept")
        check(merged.index("code\\mid\\needs.dm") < merged.index("code\\new\\lane.dm"), "ordered by the spec, not by the side's text")
        check(merged.count("code\\engine\\_generated\\gen.dm") == 1 and merged[0] == "code\\genesis_call.dme", "generated and genesis once")
    for f in failures:
        print(f"gen_dme selftest FAILED: {f}", file=sys.stderr)
    if not failures:
        print("gen_dme selftest: ok")
    return 1 if failures else 0


