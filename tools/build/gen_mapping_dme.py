#!/usr/bin/env python3
"""Generate deepquarry.mapping.dme: the dme a mapper opens in StrongDMM (code/content/variants/README.md).

  python3 tools/build/gen_mapping_dme.py            # write maps/~mapping/variant_stubs.dm and deepquarry.mapping.dme
  python3 tools/build/gen_mapping_dme.py --check    # fail when either is stale

A family that became one type and a table (tools/ci/variant_collapse.py) no longer has a type for each old sign, trash item or accessory, so
StrongDMM cannot place or show it. The mapping dme is deepquarry.dme plus one file of stub types, one per table row: `/parent/key` with the
row's vars as defaults, so the editor's palette and map view show what the row looks like. Maps keep the old paths; the loader turns them into
the parent with the row (code/content/variants/variant_alias.dm). The game is never built from this dme: a stub is skipped when the source
declares a real type at that path, and the stub file is not part of deepquarry.dme.
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "tools", "ci"))
import check_variants as cv  # noqa: E402
import variant_census as vc  # noqa: E402

STUBS = os.path.join(ROOT, "maps", "~mapping", "variant_stubs.dm")
MAPPING_DME = os.path.join(ROOT, "deepquarry.mapping.dme")
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def split_top(text):
    """Split on commas outside quotes and brackets."""
    parts, depth, cur, i = [], 0, [], 0
    in_s = None
    while i < len(text):
        c = text[i]
        if in_s:
            cur.append(c)
            if c == "\\":
                cur.append(text[i + 1])
                i += 2
                continue
            if c == in_s:
                in_s = None
        elif c in "\"'":
            in_s = c
            cur.append(c)
        elif c in "([{":
            depth += 1
            cur.append(c)
        elif c in ")]}":
            depth -= 1
            cur.append(c)
        elif c == "," and depth == 0:
            parts.append("".join(cur).strip())
            cur = []
        else:
            cur.append(c)
        i += 1
    if "".join(cur).strip():
        parts.append("".join(cur).strip())
    return parts


def table_rows(files):
    """{table name: {key: [(var, source text)]}} from the one-line rows of the variant tables."""
    out = {}
    row_re = re.compile(r'^\t"([^"]+)" = list\((.*)\),\s*$')
    for full in files:
        cur = None
        for line in open(full, encoding="utf-8", errors="replace"):
            m = cv.TABLE_START.match(line)
            if m:
                cur = m.group(1)
                out.setdefault(cur, {})
                continue
            if cur and line.startswith("))"):
                cur = None
                continue
            r = row_re.match(line.rstrip("\n"))
            if cur and r:
                pairs = []
                for part in split_top(r.group(2)):
                    v = re.match(r'^"([A-Za-z_]\w*)"\s*=\s*(.+)$', part, re.S)
                    if v:
                        pairs.append((v.group(1), v.group(2).strip()))
                out[cur][r.group(1)] = pairs
    return out


def build():
    parents = cv.load_registry()
    files = [f for f in cv.dm_files() if "dq_variants_" in open(f, encoding="utf-8", errors="replace").read()]
    rows = table_rows(files)
    declared = set(vc.analyse(ROOT))
    lines = [
        "// Stub types for the old paths of collapsed variant families, for StrongDMM only (deepquarry.mapping.dme).",
        "// GENERATED by tools/build/gen_mapping_dme.py from the variant tables (code/content/variants/); do not edit.",
        "// Not part of deepquarry.dme: the game never builds these types; the map loader turns the old paths into the parent and the row.",
        "",
    ]
    count = 0
    for parent in sorted(parents):
        table = rows.get(parents[parent])
        if not table:
            continue
        for key in sorted(table):
            path = "%s/%s" % (parent, key)
            if not IDENT.match(key) or path in declared:
                continue
            lines.append(path)
            for var_name, expr in table[key]:
                lines.append("\t%s = %s" % (var_name, expr))
            count += 1
    stubs = "\n".join(lines) + "\n"
    dme = open(os.path.join(ROOT, "deepquarry.dme"), encoding="utf-8", newline="").read()
    nl = "\r\n" if "\r\n" in dme else "\n"
    dme = dme.replace("\r\n", "\n")
    head = ("// deepquarry.mapping.dme: GENERATED by tools/build/gen_mapping_dme.py. deepquarry.dme plus the variant stub types, for StrongDMM.\n"
            "// Open this one to map; build and run deepquarry.dme.\n")
    marker = "// END_INCLUDE"
    assert marker in dme, "deepquarry.dme changed shape"
    mapping = head + dme.replace(marker, '#include "maps\\~mapping\\variant_stubs.dm"\n' + marker, 1)
    return stubs, mapping.replace("\n", nl), count


def main(argv):
    stubs, mapping, count = build()
    if "--check" in argv:
        have_stubs = open(STUBS, encoding="utf-8").read() if os.path.exists(STUBS) else ""
        have_dme = open(MAPPING_DME, encoding="utf-8", newline="").read() if os.path.exists(MAPPING_DME) else ""
        if have_stubs != stubs or have_dme != mapping:
            print("the mapping dme is stale: run python3 tools/build/gen_mapping_dme.py")
            return 1
        return 0
    os.makedirs(os.path.dirname(STUBS), exist_ok=True)
    open(STUBS, "w", encoding="utf-8", newline="\n").write(stubs)
    open(MAPPING_DME, "w", encoding="utf-8", newline="").write(mapping)
    print("wrote %s and %s (%d stub types)" % (os.path.relpath(STUBS, ROOT), os.path.relpath(MAPPING_DME, ROOT), count))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
