// Generates TypeScript types for tgui interfaces from the declared UI tables
// (doc/rewrite/systems.md section 3).
//
// A `-DUI_TYPES_DUMP` boot writes data/ui_types.json (code/datums/sys/ui.dm,
// ui_types_dump()): one entry per host type with its interfaces, UI_DATA fields
// and UI_ACT rows (UI_ACT_NESTED rows expanded per UI_SUBACT). This turns it into
// tgui/packages/tgui/interfaces/generated/<Interface>.d.ts, one file per
// interface, merging every host that opens that interface:
//
//   export type <Interface>Data = { field?: type; ... };
//   export type <Interface>Actions = { action: { arg?: type } | ...; ... };
//
// Usage: bun tools/build/lib/ui_types.ts [data/ui_types.json] [--check]
// --check writes nothing and exits 1 when a generated file is stale.

import fs from 'node:fs';
import path from 'node:path';

export const UI_TYPES_JSON = 'data/ui_types.json';
export const UI_TYPES_DIR = 'tgui/packages/tgui/interfaces/generated';

// UI_ARGK_* (code/__defines/sys_ui.dm).
const ARG_NUM = 1;
const ARG_INT = 2;
const ARG_TEXT = 3;
const ARG_BOOL = 4;
const ARG_CHOICE = 5;
const ARG_REF = 6;
const ARG_PATH = 7;
const ARG_LIST = 8;
const ARG_VALUE = 9;

export type UiArg = {
  name: string;
  kind: number;
  choices?: (string | number)[];
};

export type UiAct = {
  action: string;
  args: UiArg[];
};

export type UiField = {
  key: string;
  kind: number;
  type: string;
};

export type UiHost = {
  host: string;
  interfaces: string[];
  fields: UiField[];
  acts: Record<string, UiAct> | UiAct[];
};

const FIELD_TYPES: Record<string, string> = {
  num: 'number',
  number: 'number',
  text: 'string',
  string: 'string',
  bool: 'boolean',
  boolean: 'boolean',
  list: 'unknown[]',
  any: 'unknown',
  unknown: 'unknown',
};

function literal(value: string | number): string {
  return typeof value === 'number' ? String(value) : `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

/** The TS type of one declared arg. */
export function argType(arg: UiArg): string {
  switch (arg.kind) {
    case ARG_NUM:
    case ARG_INT:
      return 'number';
    case ARG_BOOL:
      return 'boolean | number';
    case ARG_CHOICE:
      return arg.choices?.length ? arg.choices.map(literal).join(' | ') : 'string | number';
    case ARG_TEXT:
    case ARG_REF:
    case ARG_PATH:
      return 'string';
    case ARG_LIST:
      return 'unknown[] | Record<string, unknown>';
    case ARG_VALUE:
      return 'string | number';
    default:
      return 'unknown';
  }
}

function key(name: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? name : literal(name);
}

/** A TS identifier for an interface name ("Fabrication/Lathe" -> "Fabrication_Lathe"). */
export function typeName(iface: string): string {
  const name = iface.replace(/[^\w$]/g, '_');
  return /^\d/.test(name) ? `_${name}` : name;
}

function argsObject(args: UiArg[]): string {
  if (!args.length) return 'Record<string, never>';
  return `{ ${args.map((a) => `${key(a.name)}?: ${argType(a)}`).join('; ')} }`;
}

/** interface name -> generated .d.ts content. */
export function renderUiTypes(hosts: UiHost[]): Map<string, string> {
  const byInterface = new Map<string, UiHost[]>();
  for (const host of hosts) {
    for (const iface of host.interfaces ?? []) {
      if (!iface) continue;
      if (!byInterface.has(iface)) byInterface.set(iface, []);
      byInterface.get(iface)?.push(host);
    }
  }
  const out = new Map<string, string>();
  for (const iface of [...byInterface.keys()].sort()) {
    const group = byInterface.get(iface) ?? [];
    const fields = new Map<string, Set<string>>();
    const actions = new Map<string, Set<string>>();
    for (const host of group) {
      for (const field of host.fields ?? []) {
        if (!fields.has(field.key)) fields.set(field.key, new Set());
        fields.get(field.key)?.add(FIELD_TYPES[field.type] ?? 'unknown');
      }
      const acts = Array.isArray(host.acts) ? host.acts : Object.values(host.acts ?? {});
      for (const act of acts) {
        if (!actions.has(act.action)) actions.set(act.action, new Set());
        actions.get(act.action)?.add(argsObject(act.args ?? []));
      }
    }
    const name = typeName(iface);
    const lines = [
      '// Generated by tools/build/lib/ui_types.ts from the declared UI tables',
      '// (doc/rewrite/systems.md section 3). Do not edit: rerun `tools/build/build.sh ui-types`.',
      '',
    ];
    if (fields.size) {
      lines.push(`export type ${name}Data = {`);
      for (const [field, types] of [...fields.entries()].sort()) {
        lines.push(`  ${key(field)}?: ${[...types].sort().join(' | ')};`);
      }
      lines.push('};', '');
    } else {
      lines.push(`export type ${name}Data = Record<string, unknown>;`, '');
    }
    lines.push(`export type ${name}Actions = {`);
    for (const [action, variants] of [...actions.entries()].sort()) {
      lines.push(`  ${key(action)}: ${[...variants].sort().join(' | ')};`);
    }
    lines.push('};', '');
    out.set(iface, lines.join('\n'));
  }
  return out;
}

/** The generated file of an interface. */
export function typesFile(iface: string, dir = UI_TYPES_DIR): string {
  return path.join(dir, `${iface.replace(/[^\w.-]/g, '_')}.d.ts`);
}

/**
 * Writes (or with check, compares) every generated file; removes files for interfaces that no
 * longer exist. Returns the stale or written paths.
 */
export function writeUiTypes(jsonPath = UI_TYPES_JSON, dir = UI_TYPES_DIR, check = false): string[] {
  const hosts = JSON.parse(fs.readFileSync(jsonPath, 'utf8')) as UiHost[];
  const rendered = renderUiTypes(hosts);
  const touched: string[] = [];
  const wanted = new Set<string>();
  if (!check) fs.mkdirSync(dir, { recursive: true });
  for (const [iface, content] of rendered) {
    const file = typesFile(iface, dir);
    wanted.add(path.resolve(file));
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (current === content) continue;
    touched.push(file);
    if (!check) fs.writeFileSync(file, content);
  }
  if (fs.existsSync(dir)) {
    for (const entry of fs.readdirSync(dir)) {
      const file = path.join(dir, entry);
      if (entry.endsWith('.d.ts') && !wanted.has(path.resolve(file))) {
        touched.push(file);
        if (!check) fs.rmSync(file);
      }
    }
  }
  return touched;
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const json = args.find((a) => !a.startsWith('--')) ?? UI_TYPES_JSON;
  const touched = writeUiTypes(json, UI_TYPES_DIR, check);
  if (check && touched.length) {
    console.error(`ui_types: ${touched.length} generated file(s) are stale; run tools/build/build.sh ui-types`);
    for (const file of touched) console.error(`  ${file}`);
    process.exit(1);
  }
  console.log(`ui_types: ${check ? 'checked' : 'wrote'} ${touched.length} file(s) in ${UI_TYPES_DIR}`);
}
