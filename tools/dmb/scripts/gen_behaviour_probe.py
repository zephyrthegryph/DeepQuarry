#!/usr/bin/env python3
"""Generate code/modules/unit_tests/dq_compiler_behaviour_probe.dm.

The probe checks compiler behaviour that has to match DreamMaker's: constant folding, the type filter of `for(var/T/x in L)`, the
order `typesof()` / `vars` / proc lists report, and the line numbers a thrown exception carries. Every constant expression is
evaluated twice, once as literals (the compiler may fold it) and once from variables (the VM computes it), and the test fails
when they differ; the whole result is also written to data/compiler_behaviour.txt so a DreamMaker build and a native build can
be diffed:

  DQ_COMPILER=dreammaker bash tools/dq_focused_test.sh /datum/unit_test/dq_compiler_behaviour  (copy data/compiler_behaviour.txt)
  DQ_COMPILER=native     bash tools/dq_focused_test.sh /datum/unit_test/dq_compiler_behaviour  (copy it again, diff)

  python tools/dmb/scripts/gen_behaviour_probe.py > code/modules/unit_tests/dq_compiler_behaviour_probe.dm
"""
OPERANDS = ["0", "1", "-1", "2", "3", "0.5", "-2.5", "255", "256", "65535", "16777215", "16777216", "-2147483648", "3.14159"]
BINARY = [("add", "+"), ("sub", "-"), ("mul", "*"), ("div", "/"), ("mod", "%"), ("pow", "**"), ("shl", "<<"), ("shr", ">>"),
          ("band", "&"), ("bor", "|"), ("bxor", "^"), ("eq", "=="), ("ne", "!="), ("lt", "<"), ("gt", ">"), ("le", "<="),
          ("ge", ">="), ("and", "&&"), ("or", "||"), ("equiv", "~=")]
UNARY = [("neg", "-"), ("not", "!"), ("bnot", "~")]
# Builtin functions DreamMaker folds when every argument is a literal (checked against its compiler's output by the grid).
FUNCTIONS_1 = ["round", "floor", "ceil", "sqrt", "abs", "sin", "cos", "tan", "arcsin", "arccos", "arctan", "log"]
FUNCTIONS_2 = ["round", "min", "max", "log", "arctan"]
FUNCTIONS_3 = ["clamp"]
# DreamMaker rejects constant division by zero at compile time.
SKIP_ZERO_RIGHT = {"/", "%"}
# Negative or 32-and-over shift counts are undefined in both forms.
SKIP_SHIFT = {"<<", ">>"}

TAB = "\t"


def lit(v, force=False):
    """Operands are written the way the tree writes them: bare literals, with parentheses only where precedence needs them."""
    return f"({v})" if force and v.startswith("-") else v


def invalid_domain(name, args):
    """Constant arguments DreamMaker rejects at compile time (invalid square root, arcsin/arccos outside [-1, 1], log not computable)."""
    v = [float(a) for a in args]
    if name == "sqrt":
        return v[0] < 0
    if name in ("arcsin", "arccos"):
        return abs(v[0]) > 1
    if name == "log":
        if len(v) == 1:
            return v[0] <= 0
        return v[0] <= 0 or v[0] == 1 or v[1] <= 0
    return False


def main():
    out = []
    w = out.append
    w("// GENERATED by tools/dmb/scripts/gen_behaviour_probe.py; edit the generator, not this file.")
    w("// Compiler behaviour probe: see the generator's docstring.")
    w("// The test world only: DreamChecker flags the extreme literals (precision loss).")
    w("#if defined(UNIT_TESTS)")
    w("#ifndef SPACEMAN_DMM")
    w("")
    w("/proc/compiler_probe_fmt(value)")
    w(TAB + "if(!isnum(value))")
    w(TAB + TAB + 'return "[value]"')
    w(TAB + "if(value == 0)")
    w(TAB + TAB + 'return "0"  // a folded 0 is +0 while the VM can produce -0')
    w(TAB + "return num2text(value, 12)")
    w("")
    for name, op in BINARY:
        w(f"/proc/compiler_probe_fold_{name}(list/rows, list/mismatches)")
        w(TAB + "var/x")
        w(TAB + "var/y")
        for a in OPERANDS:
            for b in OPERANDS:
                if op in SKIP_ZERO_RIGHT and (float(b) == 0 or (op == "%" and abs(float(b)) < 1)):
                    continue
                if op in SKIP_SHIFT and (float(b) < 0 or float(b) >= 32):
                    continue
                if op == "%" and float(a) == -2147483648 and float(b) == -1:
                    continue  # DreamMaker's own constant folder crashes (integer divide overflow)
                if op == "**" and (float(a) < 0 and float(b) != int(float(b)) or (float(a) == 0 and float(b) < 0)):
                    continue  # compile error "illegal: a ** b"
                key = f"{name} {a} {b}"
                w(f"{TAB}x = {lit(a, True)}")
                w(f"{TAB}y = {lit(b, True)}")
                w(f'{TAB}compiler_probe_row(rows, mismatches, "{key}", {lit(a, op == "**")} {op} {lit(b)}, x {op} y)')
    for name, op in UNARY:
        w(f"/proc/compiler_probe_fold_{name}(list/rows, list/mismatches)")
        w(TAB + "var/x")
        for a in OPERANDS:
            w(f"{TAB}x = {lit(a, True)}")
            w(f'{TAB}compiler_probe_row(rows, mismatches, "{name} {a}", {op}{lit(a, True)}, {op}x)')
    for name in FUNCTIONS_1:
        w(f"/proc/compiler_probe_fold_f1_{name}(list/rows, list/mismatches)")
        w(TAB + "var/x")
        for a in OPERANDS:
            if invalid_domain(name, [a]):
                continue
            w(f"{TAB}x = {lit(a, True)}")
            w(f'{TAB}compiler_probe_row(rows, mismatches, "f1_{name} {a}", {name}({lit(a)}), {name}(x))')
    for name in FUNCTIONS_2:
        w(f"/proc/compiler_probe_fold_f2_{name}(list/rows, list/mismatches)")
        w(TAB + "var/x")
        w(TAB + "var/y")
        for a in OPERANDS:
            for b in OPERANDS:
                if name == "round" and float(b) == 0:
                    continue
                if invalid_domain(name, [a, b]):
                    continue
                w(f"{TAB}x = {lit(a, True)}")
                w(f"{TAB}y = {lit(b, True)}")
                w(f'{TAB}compiler_probe_row(rows, mismatches, "f2_{name} {a} {b}", {name}({lit(a)}, {lit(b)}), {name}(x, y))')
    for name in FUNCTIONS_3:
        w(f"/proc/compiler_probe_fold_f3_{name}(list/rows, list/mismatches)")
        w(TAB + "var/x")
        w(TAB + "var/y")
        w(TAB + "var/z")
        for a in OPERANDS[::3]:
            for b in OPERANDS[::3]:
                for c in OPERANDS[::3]:
                    w(f"{TAB}x = {lit(a, True)}")
                    w(f"{TAB}y = {lit(b, True)}")
                    w(f"{TAB}z = {lit(c, True)}")
                    w(f'{TAB}compiler_probe_row(rows, mismatches, "f3_{name} {a} {b} {c}", {name}({lit(a)}, {lit(b)}, {lit(c)}), {name}(x, y, z))')
    w("/proc/compiler_probe_fold_ternary(list/rows, list/mismatches)")
    w(TAB + "var/x")
    for a in OPERANDS:
        w(f"{TAB}x = {lit(a, True)}")
        w(f'{TAB}compiler_probe_row(rows, mismatches, "ternary {a}", ({lit(a)} ? 11 : 22), (x ? 11 : 22))')
    w("")
    w("/// \"fold [key] = [constant form] | [variable form]\"; a mismatch within one build is a wrong fold.")
    w("/proc/compiler_probe_row(list/rows, list/mismatches, key, constant_form, variable_form)")
    w(TAB + "var/c = compiler_probe_fmt(constant_form)")
    w(TAB + "var/v = compiler_probe_fmt(variable_form)")
    w(TAB + 'rows += "fold [key] = [c] | [v]"')
    w(TAB + "if(c != v)")
    w(TAB + TAB + 'mismatches += "[key]: constant form [c], variable form [v]"')
    w("")
    names = "add sub mul div mod pow shl shr band bor bxor eq ne lt gt le ge and or equiv".split() + [n for n, _ in UNARY] + [f"f1_{n}" for n in FUNCTIONS_1] + [f"f2_{n}" for n in FUNCTIONS_2] + [f"f3_{n}" for n in FUNCTIONS_3] + ["ternary"]
    w("/proc/compiler_probe_fold_all(list/rows, list/mismatches)")
    for n in names:
        w(f"{TAB}compiler_probe_fold_{n}(rows, mismatches)")
    w("")
    w("/proc/compiler_probe_fold_branches(list/rows)")
    w(TAB + "var/n = 0")
    w(TAB + "if(1)")
    w(TAB + TAB + "n += 1")
    w(TAB + "if(0)")
    w(TAB + TAB + "n += 2")
    w(TAB + "else")
    w(TAB + TAB + "n += 4")
    w(TAB + "while(0)")
    w(TAB + TAB + "n += 8")
    w(TAB + "n += (3 | 4) ? 16 : 32")
    w(TAB + "n += (0 && 5) ? 64 : 128")
    w(TAB + 'rows += "branches [n]"')
    w("")
    w("/obj/compiler_probe_a")
    w("/obj/compiler_probe_a/compiler_probe_a2")
    w("/obj/compiler_probe_b")
    w("/mob/compiler_probe_m")
    w("/datum/compiler_probe_d")
    w("")
    w("/// Iterator type filters: how many entries each `for(var/T/x in L)` visits.")
    w("/proc/compiler_probe_iterators(list/rows)")
    w(TAB + 'var/list/L = list(new /obj/compiler_probe_a, new /mob/compiler_probe_m, new /datum/compiler_probe_d, 5, "s", new /obj/compiler_probe_b, null, new /obj/compiler_probe_a/compiler_probe_a2, new /obj/compiler_probe_a)')
    w(TAB + "var/n = 0")
    for label, typ in [("obj", "obj"), ("obj_a", "obj/compiler_probe_a"), ("obj_a2", "obj/compiler_probe_a/compiler_probe_a2"), ("mob", "mob"),
                       ("datum", "datum"), ("atom", "atom"), ("movable", "atom/movable"), ("turf", "turf")]:
        w(TAB + "n = 0")
        w(f"{TAB}for(var/{typ}/x in L)")
        w(TAB + TAB + "n++")
        w(f'{TAB}rows += "iter {label} [n]"')
    w(TAB + "n = 0")
    w(TAB + "for(var/x in L)")
    w(TAB + TAB + "n++")
    w(TAB + 'rows += "iter untyped [n]"')
    w(TAB + "n = 0")
    w(TAB + "for(var/obj/x as anything in L)")
    w(TAB + TAB + "n++")
    w(TAB + 'rows += "iter anything [n]"')
    w(TAB + "n = 0")
    w(TAB + "for(var/obj/compiler_probe_a/x in L)")
    w(TAB + TAB + "n++")
    w(TAB + TAB + "break")
    w(TAB + 'rows += "iter break [n]"')
    w(TAB + "n = 0")
    w(TAB + "for(var/obj/x in L)")
    w(TAB + TAB + "for(var/mob/y in L)")
    w(TAB + TAB + TAB + "n++")
    w(TAB + 'rows += "iter nested [n]"')
    w(TAB + "for(var/datum/compiler_probe_d/x in L)")
    w(TAB + TAB + 'rows += "iter datum_d [x.type]"')
    w(TAB + "for(var/atom/x in L)")
    w(TAB + TAB + 'rows += "iter atom_each [x.type]"')
    w(TAB + "for(var/thing in L)")
    w(TAB + TAB + "if(istype(thing, /datum))")
    w(TAB + TAB + TAB + "qdel(thing)")
    w("")
    w("/// Observable orders: typesof(), vars, proc lists.")
    w("/proc/compiler_probe_orders(list/rows)")
    for root in ["/datum", "/atom", "/obj/item", "/mob/living/carbon/human", "/turf", "/area", "/client", "/list", "/image", "/sound", "/icon", "/regex", "/savefile"]:
        w(f"{TAB}for(var/T in typesof({root}))")
        w(f'{TAB}{TAB}rows += "typesof {root} [T]"')
    for root in ["/datum", "/atom", "/atom/movable", "/obj", "/obj/item", "/mob", "/mob/living", "/mob/living/carbon/human", "/turf", "/area", "/client"]:
        w(f"{TAB}for(var/P in typesof({root}/proc))")
        w(f'{TAB}{TAB}rows += "procs {root} [P]"')
    for root in ["/mob", "/mob/living", "/mob/living/carbon/human", "/client"]:
        w(f"{TAB}for(var/P in typesof({root}/verb))")
        w(f'{TAB}{TAB}rows += "verbs {root} [P]"')
    for label, ctor in [("datum", "/datum"), ("obj", "/obj"), ("mob", "/mob"), ("movable", "/atom/movable")]:
        w(f"{TAB}var{ctor}/{label}_probe = new {ctor}")
        w(f"{TAB}for(var/v in {label}_probe.vars)")
        w(f'{TAB}{TAB}rows += "vars {label} [v]"')
        w(f"{TAB}qdel({label}_probe)")
    w(TAB + "for(var/v in world.vars)")
    w(TAB + TAB + 'rows += "vars world [v]"')
    w(TAB + "for(var/v in global.vars)")
    w(TAB + TAB + 'rows += "vars global [v]"')
    w("")
    w("/// The file:line a thrown exception and a runtime error carry.")
    w("/proc/compiler_probe_lines(list/rows)")
    for n in ["plain", "after_multiline", "in_branches", "runtime_error", "continuation"]:
        w(f"{TAB}compiler_probe_line_{n}(rows)")
    w("")
    w("/proc/compiler_probe_catch(list/rows, label, exception/e)")
    w(TAB + 'rows += "line [label] [e.file]:[e.line]"')
    w("")
    w("/proc/compiler_probe_line_plain(list/rows)")
    w(TAB + "try")
    w(TAB + TAB + 'throw new /exception("one")')
    w(TAB + "catch(var/exception/e)")
    w(TAB + TAB + 'compiler_probe_catch(rows, "plain", e)')
    w("")
    w("// A comment line and a blank line before the next procedure.")
    w("")
    w("/proc/compiler_probe_line_after_multiline(list/rows)")
    w(TAB + "var/list/spread = list(")
    w(TAB + TAB + '"a",')
    w(TAB + TAB + '"b",')
    w(TAB + TAB + '"c")')
    w(TAB + "try")
    w(TAB + TAB + 'rows += "spread [length(spread)]"')
    w(TAB + TAB + 'throw new /exception("two")')
    w(TAB + "catch(var/exception/e)")
    w(TAB + TAB + 'compiler_probe_catch(rows, "after_multiline", e)')
    w("")
    w("/proc/compiler_probe_line_in_branches(list/rows)")
    w(TAB + "for(var/i in 1 to 3)")
    w(TAB + TAB + "try")
    w(TAB + TAB + TAB + "if(i == 2)")
    w(TAB + TAB + TAB + TAB + 'throw new /exception("in branch")')
    w(TAB + TAB + TAB + "else")
    w(TAB + TAB + TAB + TAB + 'throw new /exception("in else")')
    w(TAB + TAB + "catch(var/exception/e)")
    w(TAB + TAB + TAB + 'compiler_probe_catch(rows, "branch[i]", e)')
    w("")
    w("/datum/proc/compiler_probe_missing()")
    w(TAB + "return 1")
    w("")
    w("/proc/compiler_probe_line_runtime_error(list/rows)")
    w(TAB + "var/datum/nothing = null")
    w(TAB + "try")
    w(TAB + TAB + "nothing.compiler_probe_missing()")
    w(TAB + "catch(var/exception/e)")
    w(TAB + TAB + 'compiler_probe_catch(rows, "null_call", e)')
    w(TAB + "try")
    w(TAB + TAB + "var/list/L = list(1)")
    w(TAB + TAB + 'rows += "[L[5]]"')
    w(TAB + "catch(var/exception/e2)")
    w(TAB + TAB + 'compiler_probe_catch(rows, "bad_index", e2)')
    w("")
    w("/proc/compiler_probe_line_continuation(list/rows)")
    w(TAB + 'var/text = "a" + \\')
    w(TAB + TAB + '"b"')
    w(TAB + "try")
    w(TAB + TAB + "rows += text")
    w(TAB + TAB + 'throw new /exception("after continuation")')
    w(TAB + "catch(var/exception/e)")
    w(TAB + TAB + 'compiler_probe_catch(rows, "continuation", e)')
    w("")
    w("/// The rows a compiler has to reproduce exactly (the pin): one digest per folded operator, and the small sections whole. The tree-sized")
    w("/// orders (typesof, procs, vars) are in the dump only: they change with every type the tree gains.")
    w("/proc/compiler_probe_pin_rows(list/rows)")
    w(TAB + "var/list/pins = list()")
    w(TAB + "var/list/by_op = list()")
    w(TAB + "for(var/row in rows)")
    w(TAB + TAB + 'if(copytext(row, 1, 6) == "fold ")')
    w(TAB + TAB + TAB + 'var/op = splittext(row, " ")[2]')
    w(TAB + TAB + TAB + 'var/bar = findtext(row, " | ")')
    w(TAB + TAB + TAB + "if(!by_op[op])")
    w(TAB + TAB + TAB + TAB + "by_op[op] = list()")
    w(TAB + TAB + TAB + "var/list/group = by_op[op]")
    w(TAB + TAB + TAB + "group += copytext(row, 1, bar)")
    w(TAB + TAB + 'else if(copytext(row, 1, 6) == "iter " || copytext(row, 1, 10) == "branches " || copytext(row, 1, 8) == "spread ")')
    w(TAB + TAB + TAB + "pins += row")
    w(TAB + "for(var/op in by_op)")
    w(TAB + TAB + "var/list/group = by_op[op]")
    w(TAB + TAB + 'pins += "fold [op] [length(group)] [md5(jointext(group, "\\n"))]"')
    w(TAB + "return pins")
    w("")
    w("/datum/unit_test/dq_compiler_behaviour")
    w("")
    w("/// Compiler behaviour that must match DreamMaker's, pinned from a DreamMaker build of this probe (snapshots/compiler_behaviour.txt;")
    w("/// tools/dmb/scripts/pin_behaviour.py rebuilds it from a dump). The full dump goes to data/compiler_behaviour.txt: run the test")
    w("/// under DQ_COMPILER=dreammaker and DQ_COMPILER=native and diff the two dumps to see what a failure is about.")
    w("/datum/unit_test/dq_compiler_behaviour/Run()")
    w(TAB + "var/list/rows = list()")
    w(TAB + "var/list/vm_differs = list()")
    w(TAB + "compiler_probe_fold_all(rows, vm_differs)")
    w(TAB + "compiler_probe_fold_branches(rows)")
    w(TAB + "compiler_probe_iterators(rows)")
    w(TAB + "compiler_probe_orders(rows)")
    w(TAB + "compiler_probe_lines(rows)")
    w(TAB + 'fdel("data/compiler_behaviour.txt")')
    w(TAB + 'text2file("[jointext(rows, "\\n")]\\n", "data/compiler_behaviour.txt")')
    w(TAB + "var/list/got = compiler_probe_pin_rows(rows)")
    w(TAB + 'var/list/want = splittext(file2text("code/modules/unit_tests/snapshots/compiler_behaviour.txt"), "\\n")')
    w(TAB + "var/list/problems = list()")
    w(TAB + "for(var/row in got)")
    w(TAB + TAB + "if(!(row in want))")
    w(TAB + TAB + TAB + 'problems += "got [row]"')
    w(TAB + "for(var/row in want)")
    w(TAB + TAB + 'if(length(row) && copytext(row, 1, 2) != "#" && !(row in got))')
    w(TAB + TAB + TAB + 'problems += "want [row]"')
    w(TAB + 'log_test("compiler behaviour: [length(vm_differs)] constants differ from the same expression computed by the VM (DreamMaker folds some differently; the pin holds its values)")')
    w(TAB + 'TEST_ASSERT(!length(problems), "[length(problems)] rows differ from the DreamMaker pin: [jointext(problems.Copy(1, min(length(problems) + 1, 21)), "; ")]")')
    w("")
    w("#endif")
    w("#endif")
    print("\n".join(out))


main()
