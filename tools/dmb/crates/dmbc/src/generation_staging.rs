//! Live output scratch, never a reusable file cache or a source input.
//! Unix unlinks immediately; Windows deletes on the last handle close, including
//! process exit. Payload scratch stays outside the source tree; publication-only
//! empty anchor handles temporarily keep destination directories nonempty.
use std::{
    fs::{File, OpenOptions},
    io,
    path::Path,
    sync::atomic::{AtomicU64, Ordering},
};
static NEXT: AtomicU64 = AtomicU64::new(1);
pub(crate) fn temporary_output(cache_root: &Path) -> io::Result<File> { temporary_with_sharing(cache_root, false) }

// A publication anchor has the SAME owned delete-on-close lifetime, with no
// FILE_SHARE_DELETE so its directory cannot become empty before guard release.
#[cfg(windows)]
pub(crate) fn publication_anchor(parent: &Path) -> io::Result<File> { temporary_with_sharing(parent, true) }

fn temporary_with_sharing(cache_root: &Path, anchor:bool) -> io::Result<File> {
    if !cache_root.is_absolute() {
        return Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            "generation scratch root must be absolute",
        ));
    }
    for _ in 0..16 {
        crate::daemon::control::checkpoint()?;
        let nonce = NEXT
            .fetch_update(Ordering::Relaxed, Ordering::Relaxed, |value| {
                value.checked_add(1)
            })
            .map_err(|_| io::Error::other("generation scratch identities exhausted"))?;
        let path = cache_root.join(format!(".dmbc-generation-{}-{nonce}", std::process::id()));
        let mut options = OpenOptions::new();
        options.read(true).write(true).create_new(true);
        #[cfg(windows)]
        {
            use std::os::windows::fs::OpenOptionsExt;
            const GENERIC_READ: u32 = 0x80000000;
            const GENERIC_WRITE: u32 = 0x40000000;
            const DELETE_ACCESS: u32 = 0x00010000;
            const FILE_SHARE_READ: u32 = 1;
            const FILE_SHARE_WRITE: u32 = 2;
            const FILE_SHARE_DELETE: u32 = 4;
            const FILE_ATTRIBUTE_TEMPORARY: u32 = 0x00000100;
            const FILE_FLAG_DELETE_ON_CLOSE: u32 = 0x04000000;
            options
                .access_mode(GENERIC_READ | GENERIC_WRITE | DELETE_ACCESS)
                .share_mode(FILE_SHARE_READ | FILE_SHARE_WRITE | if anchor { 0 } else { FILE_SHARE_DELETE })
                .custom_flags(FILE_ATTRIBUTE_TEMPORARY | FILE_FLAG_DELETE_ON_CLOSE);
        }
        match options.open(&path) {
            Ok(file) => {
                #[cfg(not(windows))]
                std::fs::remove_file(&path)?;
                return Ok(file);
            }
            Err(actual) if actual.kind() == io::ErrorKind::AlreadyExists => continue,
            Err(actual) => return Err(actual),
        }
    }
    Err(io::Error::new(
        io::ErrorKind::AlreadyExists,
        "generation scratch namespace collision limit reached",
    ))
}
#[cfg(test)]
mod tests {
    use super::*;
    use std::io::{Read, Seek, SeekFrom, Write};
    fn entries(root: &Path) -> usize {
        std::fs::read_dir(root).unwrap().map(Result::unwrap).count()
    }
    #[test]
    fn generation_temporary_output_is_seekable_and_leaves_no_file_after_close() {
        let root = crate::test_scratch::dir("generation-output-close");
        let before = entries(&root);
        let mut file = temporary_output(&root).unwrap();
        file.write_all(b"actual final generated bytes\0\n").unwrap();
        file.seek(SeekFrom::Start(0)).unwrap();
        let mut actual = Vec::new();
        file.read_to_end(&mut actual).unwrap();
        assert_eq!(actual, b"actual final generated bytes\0\n");
        drop(file);
        assert_eq!(entries(&root), before);
    }
    #[test]
    fn generation_temporary_output_cleanup_survives_error_unwind() {
        let root = crate::test_scratch::dir("generation-output-unwind");
        let before = entries(&root);
        let result = std::panic::catch_unwind(|| {
            let mut file = temporary_output(&root).unwrap();
            file.write_all(b"never publish this partial output")
                .unwrap();
            panic!("generation staging failure");
        });
        assert!(result.is_err());
        assert_eq!(entries(&root), before);
    }
    #[test]
    fn generation_temporary_output_preserves_real_open_error() {
        let root = crate::test_scratch::dir("generation-output-error");
        let missing = root.join("absent");
        assert_eq!(
            temporary_output(&missing).err().unwrap().kind(),
            io::ErrorKind::NotFound
        );
        assert_eq!(entries(&root), 0);
        assert!(temporary_output(Path::new("relative")).is_err());
    }
}
