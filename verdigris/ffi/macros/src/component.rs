//! `#[vg::component]` (`doc/rewrite/rust_architecture.md` §5): a component
//! crate writes the struct and nothing else.
//!
//! Everything generated here is `byondapi`-free and builds on the host:
//! - the `Default` impl (from each field's `default = ...`);
//! - `FooKind`, the `vg_core::owner::Domain` marker the stores, overlay,
//!   command path and watches key on;
//! - `FooCommand`: one variant per `config`/`input` field (plus `FieldAt`
//!   for array fields) and the generic `Adjust(field, index, delta)` used
//!   for take reconciliation of `conserve`d fields;
//! - `impl vg_core::component::Component`: the numeric field table and
//!   `get_field`/`set_command`/`adjust_command` by field id, which is all the
//!   generic FFI surface in `vg-ffi` needs (there are no per-component
//!   binds);
//! - `impl vg_core::channel::Channels for FooKind`: one watch channel per
//!   numeric field and computed readout, so every component is watchable.
//!
//! The DM side (typed `get_*`/`set_*` wrappers, `init_*` vars, event
//! dispatch) is generated by `tools/build/lib/verdigris_bindings.ts` from
//! the same declaration, calling the generic `vg_component_*` binds with the
//! field ids this macro assigns (declaration order, computed readouts last).
//!
//! Grammar:
//!
//! ```text
//! #[vg::component(domain = gas, kind = 1, dm = "/obj/...",
//!                 owner = worker|main,              (default worker)
//!                 computed = [pressure, total])]    (read-only readouts:
//!                                                    `fn pressure(&self) -> f32`)
//! struct Foo {
//!     #[vg(config, unit = "kPa", range = 0.0..=10.0, default = 1.0, on_invalid = clamp|reject,
//!          hysteresis = 0.1)]
//!     a: f32,
//!     #[vg(input, from = [construction, integrity])]
//!     b: bool,
//!     #[vg(state, unit = "mol", conserve = "moles")]
//!     c: [f32; N],
//! }
//! ```

use proc_macro2::{Span, TokenStream};
use quote::{format_ident, quote};
use syn::parse::{Parse, ParseStream};
use syn::spanned::Spanned;
use syn::{Ident, LitInt, LitStr, Token};

// --- `#[component(...)]` on the struct ---------------------------------

struct ComponentArgs {
    domain: Ident,
    kind: LitInt,
    /// The DM type this component binds to, or `None` for a component with
    /// no natural DM owner (a bare-entity row like a pipe device's flow/
    /// valve, `ffi/src/pipes.rs`): `tools/build/lib/verdigris_bindings.ts`
    /// then generates free-function `vg_bind_<domain>`/`get_*`/`set_*`
    /// procs taking the entity number directly, instead of per-type ones.
    dm: Option<LitStr>,
    owner_main: bool,
    computed: Vec<Ident>,
}

impl Parse for ComponentArgs {
    fn parse(input: ParseStream) -> syn::Result<Self> {
        let mut domain = None;
        let mut kind = None;
        let mut dm = None;
        let mut owner_main = false;
        let mut computed = Vec::new();
        while !input.is_empty() {
            let key: Ident = input.parse()?;
            input.parse::<Token![=]>()?;
            match key.to_string().as_str() {
                "domain" => domain = Some(input.parse()?),
                "kind" => kind = Some(input.parse()?),
                "dm" => dm = Some(input.parse()?),
                "owner" => {
                    let o: Ident = input.parse()?;
                    owner_main = match o.to_string().as_str() {
                        "main" => true,
                        "worker" => false,
                        other => {
                            return Err(syn::Error::new(
                                o.span(),
                                format!("owner must be `main` or `worker`, got `{other}`"),
                            ));
                        }
                    };
                }
                "computed" => {
                    let content;
                    syn::bracketed!(content in input);
                    let list: syn::punctuated::Punctuated<Ident, Token![,]> =
                        content.parse_terminated(Ident::parse, Token![,])?;
                    computed = list.into_iter().collect();
                }
                "ports" => {
                    // Accepted and ignored: which pipe ports a gas device
                    // exposes is the flow law's business, not the binding
                    // layer's. `[input, output]`.
                    let content;
                    syn::bracketed!(content in input);
                    let _: syn::punctuated::Punctuated<Ident, Token![,]> =
                        content.parse_terminated(Ident::parse, Token![,])?;
                }
                other => {
                    return Err(syn::Error::new(
                        key.span(),
                        format!("unknown #[component] argument `{other}`"),
                    ));
                }
            }
            if input.peek(Token![,]) {
                input.parse::<Token![,]>()?;
            }
        }
        Ok(Self {
            domain: domain.ok_or_else(|| input.error("#[component] needs `domain = ...`"))?,
            kind: kind.ok_or_else(|| {
                input.error(
                    "#[component] needs `kind = <n>` (a small integer unique within the domain)",
                )
            })?,
            dm,
            owner_main,
            computed,
        })
    }
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum Role {
    Config,
    State,
    Input,
}

struct FieldAttr {
    role: Role,
    unit: Option<LitStr>,
    range: Option<(syn::Expr, syn::Expr)>,
    default: Option<syn::Expr>,
    on_invalid: Option<Ident>,
    conserve: Option<LitStr>,
    hysteresis: Option<syn::Expr>,
}

impl Parse for FieldAttr {
    fn parse(input: ParseStream) -> syn::Result<Self> {
        let role_ident: Ident = input.parse()?;
        let role = match role_ident.to_string().as_str() {
            "config" => Role::Config,
            "state" => Role::State,
            "input" => Role::Input,
            other => {
                return Err(syn::Error::new(
                    role_ident.span(),
                    format!("unknown field role `{other}` (expected config, state or input)"),
                ));
            }
        };
        let mut attr = FieldAttr {
            role,
            unit: None,
            range: None,
            default: None,
            on_invalid: None,
            conserve: None,
            hysteresis: None,
        };
        while input.peek(Token![,]) {
            input.parse::<Token![,]>()?;
            if input.is_empty() {
                break;
            }
            let key: Ident = input.parse()?;
            input.parse::<Token![=]>()?;
            match key.to_string().as_str() {
                "unit" => attr.unit = Some(input.parse()?),
                "range" => {
                    let r: syn::ExprRange = input.parse()?;
                    let start = r.start.clone().ok_or_else(|| {
                        syn::Error::new(r.span(), "range needs a start, e.g. `0.0..=10.0`")
                    })?;
                    let end = r.end.clone().ok_or_else(|| {
                        syn::Error::new(r.span(), "range needs an end, e.g. `0.0..=10.0`")
                    })?;
                    attr.range = Some((*start, *end));
                }
                "default" => attr.default = Some(input.parse()?),
                "on_invalid" => attr.on_invalid = Some(input.parse()?),
                "conserve" => attr.conserve = Some(input.parse()?),
                "hysteresis" => attr.hysteresis = Some(input.parse()?),
                "from" => {
                    // Documentation for the reconciler and the DM
                    // generator (which hooks known sources); nothing to
                    // generate on the Rust side.
                    let content;
                    syn::bracketed!(content in input);
                    let _: syn::punctuated::Punctuated<Ident, Token![,]> =
                        content.parse_terminated(Ident::parse, Token![,])?;
                }
                other => {
                    return Err(syn::Error::new(
                        key.span(),
                        format!("unknown field attribute `{other}`"),
                    ));
                }
            }
        }
        Ok(attr)
    }
}

struct ParsedField {
    ident: Ident,
    ty: syn::Type,
    attr: FieldAttr,
}

const NUMERIC: [&str; 12] = [
    "f32", "f64", "u8", "u16", "u32", "u64", "i8", "i16", "i32", "i64", "usize", "bool",
];

fn type_name(ty: &syn::Type) -> String {
    quote!(#ty).to_string().replace(' ', "")
}

fn is_numeric(ty: &syn::Type) -> bool {
    NUMERIC.contains(&type_name(ty).as_str())
}

fn is_bool(ty: &syn::Type) -> bool {
    type_name(ty) == "bool"
}

impl ParsedField {
    /// `(element type, length expression)` for a `[T; N]` field.
    fn array(&self) -> Option<(&syn::Type, &syn::Expr)> {
        match &self.ty {
            syn::Type::Array(a) => Some((&a.elem, &a.len)),
            _ => None,
        }
    }

    fn scalar_ty(&self) -> &syn::Type {
        self.array().map_or(&self.ty, |(e, _)| e)
    }

    fn numeric(&self) -> bool {
        is_numeric(self.scalar_ty())
    }

    fn len_expr(&self) -> TokenStream {
        match self.array() {
            Some((_, n)) => quote! { (#n) as u16 },
            None => quote! { 1u16 },
        }
    }
}

fn pascal_case(ident: &Ident) -> Ident {
    let mut out = String::new();
    for part in ident.to_string().split('_') {
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            out.extend(first.to_uppercase());
            out.extend(chars);
        }
    }
    format_ident!("{out}", span = ident.span())
}

/// `Pump` -> `pump`, `GasMix` -> `gas_mix`: the prefix every generated DM
/// name shares. Mirrors `tools/build/lib/verdigris_bindings.ts`'s `snake()`
/// character for character (underscore before an uppercase letter that
/// follows a lowercase letter or digit, then lowercase).
pub(crate) fn snake_case(ident: &Ident) -> String {
    let name = ident.to_string();
    let mut out = String::with_capacity(name.len() + 4);
    let chars: Vec<char> = name.chars().collect();
    for (i, &c) in chars.iter().enumerate() {
        if i > 0 && c.is_ascii_uppercase() {
            let prev = chars[i - 1];
            if prev.is_ascii_lowercase() || prev.is_ascii_digit() {
                out.push('_');
            }
        }
        out.extend(c.to_lowercase());
    }
    out
}

/// Expands `#[component(...)] struct Foo { ... }`.
pub fn expand(
    attr: proc_macro::TokenStream,
    item: proc_macro::TokenStream,
) -> proc_macro::TokenStream {
    let args = syn::parse_macro_input!(attr as ComponentArgs);
    let input = syn::parse_macro_input!(item as syn::ItemStruct);
    match expand_inner(&args, input) {
        Ok(ts) => ts.into(),
        Err(e) => e.to_compile_error().into(),
    }
}

#[allow(clippy::too_many_lines)]
fn expand_inner(args: &ComponentArgs, mut input: syn::ItemStruct) -> syn::Result<TokenStream> {
    let syn::Fields::Named(fields) = &mut input.fields else {
        return Err(syn::Error::new(
            input.span(),
            "#[component] needs a struct with named fields",
        ));
    };

    let mut parsed = Vec::new();
    for field in &mut fields.named {
        let Some(ident) = field.ident.clone() else {
            continue;
        };
        let mut vg_attr = None;
        let mut kept = Vec::new();
        for a in field.attrs.drain(..) {
            if a.path().is_ident("vg") {
                if vg_attr.is_some() {
                    return Err(syn::Error::new(
                        a.span(),
                        "a field may have only one #[vg(...)]",
                    ));
                }
                let tokens = match &a.meta {
                    syn::Meta::List(list) => list.tokens.clone(),
                    _ => return Err(syn::Error::new(a.span(), "expected #[vg(role, ...)]")),
                };
                vg_attr = Some(syn::parse2::<FieldAttr>(tokens)?);
            } else {
                kept.push(a);
            }
        }
        field.attrs = kept;
        let Some(attr) = vg_attr else {
            return Err(syn::Error::new(
                ident.span(),
                format!("field `{ident}` needs a #[vg(config|state|input, ...)] attribute"),
            ));
        };
        if attr.role == Role::Config && attr.default.is_none() {
            return Err(syn::Error::new(
                ident.span(),
                "a config field needs `default = ...`",
            ));
        }
        let pf = ParsedField {
            ident,
            ty: field.ty.clone(),
            attr,
        };
        if pf.attr.conserve.is_some() && (!pf.numeric() || is_bool(pf.scalar_ty())) {
            return Err(syn::Error::new(
                pf.ident.span(),
                "`conserve` needs a numeric (non-bool) field",
            ));
        }
        parsed.push(pf);
    }

    input.attrs.push(syn::parse_quote! {
        #[derive(::std::clone::Clone, ::std::fmt::Debug, ::std::cmp::PartialEq)]
    });

    let struct_ident = input.ident.clone();
    let vis = input.vis.clone();
    let kind_ident = format_ident!("{struct_ident}Kind");
    let command_ident = format_ident!("{struct_ident}Command");
    let domain_str = args.domain.to_string();
    let kind_lit = &args.kind;
    let dm_str = args.dm.as_ref().map(LitStr::value).unwrap_or_default();
    let lower = snake_case(&struct_ident);
    let owner = if args.owner_main {
        quote! { ::vg_core::component::Ownership::Main }
    } else {
        quote! { ::vg_core::component::Ownership::Worker }
    };

    // --- Default -----------------------------------------------------------
    let default_fields = parsed.iter().map(|f| {
        let ident = &f.ident;
        match &f.attr.default {
            Some(expr) if f.array().is_some() => quote! { #ident: #expr },
            Some(expr) => quote! { #ident: (#expr) as _ },
            None => quote! { #ident: ::std::default::Default::default() },
        }
    });

    // --- Commands ---------------------------------------------------------
    let command_fields: Vec<&ParsedField> = parsed
        .iter()
        .filter(|f| matches!(f.attr.role, Role::Config | Role::Input))
        .collect();
    let command_variants = command_fields.iter().flat_map(|f| {
        let variant = pascal_case(&f.ident);
        let ty = &f.ty;
        let whole = quote! { #variant(#ty) };
        match f.array() {
            Some((elem, _)) => {
                let at_variant = format_ident!("{variant}At");
                vec![whole, quote! { #at_variant(usize, #elem) }]
            }
            None => vec![whole],
        }
    });
    let apply_arms = command_fields.iter().flat_map(|f| {
        let variant = pascal_case(&f.ident);
        let ident = &f.ident;
        let whole =
            quote! { #command_ident::#variant(v) => value.#ident = ::std::clone::Clone::clone(v) };
        match f.array() {
            Some(_) => {
                let at_variant = format_ident!("{variant}At");
                vec![
                    whole,
                    quote! {
                        #command_ident::#at_variant(i, v) => {
                            if let ::std::option::Option::Some(slot) = value.#ident.get_mut(*i) {
                                *slot = ::std::clone::Clone::clone(v);
                            }
                        }
                    },
                ]
            }
            None => vec![whole],
        }
    });

    // --- Validators (config fields) -------------------------------------
    let validators = parsed.iter().filter(|f| f.attr.role == Role::Config).flat_map(|f| {
        let ident = &f.ident;
        let scalar_ty = f.scalar_ty();
        let call = |v: TokenStream| -> Result<TokenStream, TokenStream> {
            match &f.attr.range {
                Some((min, max)) => {
                    let on_invalid = f
                        .attr
                        .on_invalid
                        .clone()
                        .unwrap_or_else(|| format_ident!("clamp", span = Span::call_site()));
                    match on_invalid.to_string().as_str() {
                        "clamp" => Ok(quote! { ::vg_core::component::clamp(#v, (#min) as #scalar_ty, (#max) as #scalar_ty) }),
                        "reject" => Ok(quote! { ::vg_core::component::reject_range(#v, (#min) as #scalar_ty, (#max) as #scalar_ty) }),
                        other => Err(syn::Error::new(
                            on_invalid.span(),
                            format!("on_invalid must be `clamp` or `reject`, got `{other}`"),
                        )
                        .to_compile_error()),
                    }
                }
                None => Ok(quote! { ::vg_core::component::identity(#v) }),
            }
        };
        let at_call = match call(quote! { v }) {
            Ok(c) => c,
            Err(e) => return vec![e],
        };
        match f.array() {
            Some((elem_ty, _)) => {
                let fn_ident = format_ident!("validate_{ident}");
                let at_fn_ident = format_ident!("validate_{ident}_at");
                let ty = &f.ty;
                vec![
                    quote! {
                        /// Validates one element (the field's `on_invalid` rule).
                        pub fn #at_fn_ident(v: #elem_ty) -> ::std::result::Result<#elem_ty, ::vg_core::component::FieldError> {
                            #at_call
                        }
                    },
                    quote! {
                        /// Validates every element.
                        pub fn #fn_ident(v: #ty) -> ::std::result::Result<#ty, ::vg_core::component::FieldError> {
                            let mut out = v;
                            for x in &mut out {
                                *x = Self::#at_fn_ident(*x)?;
                            }
                            ::std::result::Result::Ok(out)
                        }
                    },
                ]
            }
            None => {
                let fn_ident = format_ident!("validate_{ident}");
                vec![quote! {
                    /// Validates a value (the field's `on_invalid` rule).
                    pub fn #fn_ident(v: #scalar_ty) -> ::std::result::Result<#scalar_ty, ::vg_core::component::FieldError> {
                        #at_call
                    }
                }]
            }
        }
    });

    // --- Field table ------------------------------------------------------
    let computed = &args.computed;
    let n_stored = parsed.len();
    let field_schemas = parsed.iter().map(|f| {
        let name = f.ident.to_string();
        let role = match f.attr.role {
            Role::Config => quote! { ::vg_core::component::FieldRole::Config },
            Role::State => quote! { ::vg_core::component::FieldRole::State },
            Role::Input => quote! { ::vg_core::component::FieldRole::Input },
        };
        let unit = match &f.attr.unit {
            Some(u) => quote! { ::std::option::Option::Some(#u) },
            None => quote! { ::std::option::Option::None },
        };
        let conserve = match &f.attr.conserve {
            Some(q) => quote! { ::std::option::Option::Some(#q) },
            None => quote! { ::std::option::Option::None },
        };
        let len = f.len_expr();
        let numeric = f.numeric();
        quote! {
            ::vg_core::component::FieldSchema {
                name: #name,
                role: #role,
                unit: #unit,
                len: #len,
                numeric: #numeric,
                conserve: #conserve,
            }
        }
    });
    let computed_schemas = computed.iter().map(|c| {
        let name = c.to_string();
        quote! {
            ::vg_core::component::FieldSchema {
                name: #name,
                role: ::vg_core::component::FieldRole::Computed,
                unit: ::std::option::Option::None,
                len: 1,
                numeric: true,
                conserve: ::std::option::Option::None,
            }
        }
    });

    // get_field
    let get_arms = parsed.iter().enumerate().map(|(i, f)| {
        #[allow(clippy::cast_possible_truncation)]
        let id = i as u16;
        let ident = &f.ident;
        if !f.numeric() {
            return quote! { #id => ::std::option::Option::None };
        }
        match f.array() {
            Some(_) => quote! {
                #id => self.#ident.get(index).map(|v| ::vg_core::component::FieldValue::to_f64(*v))
            },
            None => quote! {
                #id => (index == 0).then(|| ::vg_core::component::FieldValue::to_f64(self.#ident))
            },
        }
    });
    let get_computed_arms = computed.iter().enumerate().map(|(j, c)| {
        #[allow(clippy::cast_possible_truncation)]
        let id = (n_stored + j) as u16;
        quote! { #id => (index == 0).then(|| ::vg_core::component::FieldValue::to_f64(self.#c())) }
    });

    // set_command
    let set_arms = parsed.iter().enumerate().map(|(i, f)| {
        #[allow(clippy::cast_possible_truncation)]
        let id = i as u16;
        let name = f.ident.to_string();
        let variant = pascal_case(&f.ident);
        if f.attr.role == Role::State {
            return quote! { #id => ::std::result::Result::Err(::vg_core::component::ComponentError::ReadOnly { field: #name }) };
        }
        if !f.numeric() {
            return quote! { #id => ::std::result::Result::Err(::vg_core::component::ComponentError::NoField { field }) };
        }
        let scalar_ty = f.scalar_ty();
        let convert = quote! { <#scalar_ty as ::vg_core::component::FieldValue>::from_f64(value) };
        let validated = |fn_ident: Ident| {
            quote! {
                #struct_ident::#fn_ident(#convert).map_err(|reason| ::vg_core::component::ComponentError::Field { field: #name, reason })?
            }
        };
        let is_config = f.attr.role == Role::Config;
        match f.array() {
            Some((_, len)) => {
                let at_variant = format_ident!("{variant}At");
                let elem = if is_config {
                    validated(format_ident!("validate_{}_at", f.ident))
                } else {
                    convert.clone()
                };
                quote! {
                    #id => {
                        let v = #elem;
                        match index {
                            ::std::option::Option::Some(i) if i < (#len) as usize => ::std::result::Result::Ok(#command_ident::#at_variant(i, v)),
                            ::std::option::Option::Some(_) => ::std::result::Result::Err(::vg_core::component::ComponentError::NoField { field }),
                            ::std::option::Option::None => ::std::result::Result::Ok(#command_ident::#variant([v; #len])),
                        }
                    }
                }
            }
            None => {
                let v = if is_config {
                    validated(format_ident!("validate_{}", f.ident))
                } else {
                    convert
                };
                quote! {
                    #id => {
                        if index.is_some_and(|i| i != 0) {
                            return ::std::result::Result::Err(::vg_core::component::ComponentError::NoField { field });
                        }
                        ::std::result::Result::Ok(#command_ident::#variant(#v))
                    }
                }
            }
        }
    });
    let set_computed_arms = computed.iter().enumerate().map(|(j, c)| {
        #[allow(clippy::cast_possible_truncation)]
        let id = (n_stored + j) as u16;
        let name = c.to_string();
        quote! { #id => ::std::result::Result::Err(::vg_core::component::ComponentError::ReadOnly { field: #name }) }
    });

    // Conserved fields: adjust + totals.
    let conserved: Vec<(u16, &ParsedField)> = parsed
        .iter()
        .enumerate()
        .filter(|(_, f)| f.attr.conserve.is_some())
        .map(|(i, f)| {
            #[allow(clippy::cast_possible_truncation)]
            (i as u16, f)
        })
        .collect();
    let conserves = !conserved.is_empty();
    let adjust_cmd_arms = conserved.iter().map(|(id, f)| {
        let len = f.len_expr();
        quote! {
            #id => {
                if index >= usize::from(#len) {
                    return ::std::result::Result::Err(::vg_core::component::ComponentError::NoField { field });
                }
                ::std::result::Result::Ok(#command_ident::Adjust(field, index, delta))
            }
        }
    });
    let adjust_field_arms = conserved.iter().map(|(id, f)| {
        let ident = &f.ident;
        match f.array() {
            Some(_) => quote! {
                #id => self.#ident.get_mut(index).map_or(0.0, |slot| ::vg_core::component::adjust_value(slot, delta))
            },
            None => quote! {
                #id => if index == 0 { ::vg_core::component::adjust_value(&mut self.#ident, delta) } else { 0.0 }
            },
        }
    });
    let conserved_visits = conserved.iter().map(|(_, f)| {
        let ident = &f.ident;
        let q = f.attr.conserve.as_ref().expect("filtered");
        match f.array() {
            Some(_) => quote! {
                visit(#q, self.#ident.iter().map(|v| ::vg_core::component::FieldValue::to_f64(*v)).sum::<f64>());
            },
            None => quote! {
                visit(#q, ::vg_core::component::FieldValue::to_f64(self.#ident));
            },
        }
    });

    // Channels: one per numeric field and computed readout.
    let channel_decls = parsed.iter().filter(|f| f.numeric()).map(|f| {
        let ident = &f.ident;
        let name = f.ident.to_string();
        let unit = match &f.attr.unit {
            Some(u) => quote! { ::vg_core::component::channel_unit(#u) },
            None => quote! { ::vg_core::channel::Unit::None },
        };
        let hysteresis = match &f.attr.hysteresis {
            Some(h) => quote! { (#h) as f32 },
            None => quote! { 0.0 },
        };
        let (kind, extract) = match f.array() {
            Some((_, len)) => (
                quote! { ::vg_core::channel::ValueKind::Vector((#len) as u8) },
                quote! {
                    |v: &#struct_ident, out: &mut [f32]| {
                        for (o, x) in out.iter_mut().zip(v.#ident.iter()) {
                            #[allow(clippy::cast_possible_truncation)]
                            { *o = ::vg_core::component::FieldValue::to_f64(*x) as f32; }
                        }
                    }
                },
            ),
            None if is_bool(&f.ty) => (
                quote! { ::vg_core::channel::ValueKind::Enum(2) },
                quote! { |v: &#struct_ident, out: &mut [f32]| { out[0] = if v.#ident { 1.0 } else { 0.0 }; } },
            ),
            None => (
                quote! { ::vg_core::channel::ValueKind::Scalar },
                quote! {
                    |v: &#struct_ident, out: &mut [f32]| {
                        #[allow(clippy::cast_possible_truncation)]
                        { out[0] = ::vg_core::component::FieldValue::to_f64(v.#ident) as f32; }
                    }
                },
            ),
        };
        quote! {
            ::vg_core::channel::ChannelDecl {
                name: #name,
                kind: #kind,
                unit: #unit,
                hysteresis: #hysteresis,
                extract: #extract,
            }
        }
    });
    let computed_channels = computed.iter().map(|c| {
        let name = c.to_string();
        quote! {
            ::vg_core::channel::ChannelDecl {
                name: #name,
                kind: ::vg_core::channel::ValueKind::Scalar,
                unit: ::vg_core::channel::Unit::None,
                hysteresis: 0.0,
                extract: |v: &#struct_ident, out: &mut [f32]| {
                    #[allow(clippy::cast_possible_truncation)]
                    { out[0] = ::vg_core::component::FieldValue::to_f64(v.#c()) as f32; }
                },
            }
        }
    });

    let field_name_strs: Vec<String> = parsed.iter().map(|f| f.ident.to_string()).collect();
    let field_count = parsed.len();

    Ok(quote! {
        #input

        #[doc = "Domain marker for the stores, overlay and watches (generated by #[vg::component])."]
        #[derive(::std::clone::Clone, ::std::marker::Copy, ::std::fmt::Debug, ::std::default::Default, ::std::cmp::PartialEq, ::std::cmp::Eq)]
        #vis struct #kind_ident;

        impl ::std::default::Default for #struct_ident {
            fn default() -> Self {
                Self { #(#default_fields),* }
            }
        }

        impl ::vg_core::owner::Domain for #kind_ident {
            type Value = #struct_ident;
            type Command = #command_ident;
            const NAME: &'static str = #lower;
            const CONSERVES: bool = #conserves;

            fn apply(value: &mut #struct_ident, cmd: &#command_ident) -> ::vg_core::owner::Applied {
                match cmd {
                    #(#apply_arms,)*
                    #command_ident::Adjust(field, index, delta) => {
                        return ::vg_core::owner::Applied { shortfall: value.adjust_field(*field, *index, *delta) };
                    }
                }
                ::vg_core::owner::Applied::default()
            }

            fn conserved(value: &#struct_ident, visit: &mut dyn FnMut(&'static str, f64)) {
                <#struct_ident as ::vg_core::component::Component>::conserved(value, visit);
            }
        }

        /// DM-originated writes (generated by #[vg::component]).
        #[derive(::std::clone::Clone, ::std::fmt::Debug, ::std::cmp::PartialEq)]
        #vis enum #command_ident {
            #(#command_variants,)*
            /// Take reconciliation: `(field, index, delta)` on a `conserve`d
            /// field, applied to the owner's current value.
            Adjust(u16, usize, f64),
        }

        impl #struct_ident {
            /// Field names in declaration order.
            pub const FIELD_NAMES: [&'static str; #field_count] = [#(#field_name_strs),*];

            #(#validators)*

            /// This component's schema, for the generator and `vg_describe()`.
            #[must_use]
            pub fn schema() -> ::vg_core::component::Schema {
                ::vg_core::component::Schema::of::<Self>()
            }

            /// The `Adjust` command's apply: returns the removal shortfall.
            #[allow(unused_variables)]
            fn adjust_field(&mut self, field: u16, index: usize, delta: f64) -> f32 {
                match field {
                    #(#adjust_field_arms,)*
                    _ => 0.0,
                }
            }
        }

        impl ::vg_core::component::Component for #struct_ident {
            type Kind = #kind_ident;
            const NAME: &'static str = #lower;
            const DOMAIN: &'static str = #domain_str;
            const DOMAIN_ID: u8 = ::vg_core::component::domain_id(#domain_str);
            const KIND: u16 = #kind_lit;
            const DM_TYPE: &'static str = #dm_str;
            const OWNER: ::vg_core::component::Ownership = #owner;
            const FIELDS: &'static [::vg_core::component::FieldSchema] = &[
                #(#field_schemas,)*
                #(#computed_schemas,)*
            ];

            #[allow(unused_variables)]
            fn get_field(&self, field: ::vg_core::component::FieldId, index: usize) -> ::std::option::Option<f64> {
                match field {
                    #(#get_arms,)*
                    #(#get_computed_arms,)*
                    _ => ::std::option::Option::None,
                }
            }

            #[allow(unused_variables, unreachable_code)]
            fn set_command(
                field: ::vg_core::component::FieldId,
                index: ::std::option::Option<usize>,
                value: f64,
            ) -> ::std::result::Result<#command_ident, ::vg_core::component::ComponentError> {
                match field {
                    #(#set_arms,)*
                    #(#set_computed_arms,)*
                    _ => ::std::result::Result::Err(::vg_core::component::ComponentError::NoField { field }),
                }
            }

            #[allow(unused_variables)]
            fn adjust_command(
                field: ::vg_core::component::FieldId,
                index: usize,
                delta: f64,
            ) -> ::std::result::Result<#command_ident, ::vg_core::component::ComponentError> {
                match field {
                    #(#adjust_cmd_arms,)*
                    _ => ::std::result::Result::Err(::vg_core::component::ComponentError::NotConserved {
                        field: <Self as ::vg_core::component::Component>::FIELDS
                            .get(usize::from(field))
                            .map_or("?", |f| f.name),
                    }),
                }
            }

            #[allow(unused_variables)]
            fn conserved(&self, visit: &mut dyn FnMut(&'static str, f64)) {
                #(#conserved_visits)*
            }
        }

        impl ::vg_core::channel::Channels for #kind_ident {
            const CHANNELS: &'static [::vg_core::channel::ChannelDecl<#struct_ident>] = &[
                #(#channel_decls,)*
                #(#computed_channels,)*
            ];
        }

        const _: () = assert!(
            #kind_lit < 256,
            "component kinds must be below 256 (event headers carry them in 8 bits)"
        );
    })
}
