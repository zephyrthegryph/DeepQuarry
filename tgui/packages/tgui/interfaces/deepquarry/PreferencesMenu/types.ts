// DQAdd — wire shape for the new auto-rendered Character Setup window.
// Mirrors /datum/preference_middleware/character_setup.get_ui_data() on the DM side.

export type PrefWidgetKind =
  | 'auto'
  | 'text'
  | 'longtext'
  | 'number'
  | 'slider'
  | 'boolean'
  | 'color'
  | 'dropdown'
  | 'radio'
  | 'thumbgrid'
  | 'multi'
  | 'editor'
  | 'hidden';

export type PrefWidgetItem = {
  type: 'widget';
  key: string;
  /// Optional UI-side label override. When null the auto-renderer titleCases the key.
  label?: string | null;
  widget: PrefWidgetKind;
  value: unknown;
  props: Record<string, unknown>;
  choices?: string[] | Record<string, string>;
  thumbnails?: Record<string, { icon: string; icon_state: string }>;
};

export type PrefEditorItem = {
  type: 'editor';
  key: string;
  sort_order: number;
  display_name: string | null;
  data: Record<string, unknown>;
};

export type PrefGroupItem = PrefWidgetItem | PrefEditorItem;

export type PrefGroup = {
  group: string;
  items: PrefGroupItem[];
};

export type PrefCategory = {
  category: string;
  groups: PrefGroup[];
};

export type CharacterPreviewAssets = {
  south?: string;
  north?: string;
  east?: string;
  west?: string;
  bg?: string;
};

export type CharacterSetupData = {
  dq_categories: PrefCategory[];
  dq_editor_static?: Record<string, Record<string, unknown>>;
  /// Server-rendered base64 PNGs of the mannequin (one per cardinal
  /// direction) plus the background icon. Generated by
  /// /datum/preferences/update_character_previews via getFlatIcon +
  /// icon2base64 — see code/modules/client/preferences.dm. React wraps
  /// each value in a `data:image/png;base64,…` URI at render time.
  character_preview_assets?: CharacterPreviewAssets;
};
